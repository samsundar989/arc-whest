import numpy as np
import flopscope as flops, flopscope.numpy as fnp
def bill(name, fn):
    with flops.BudgetContext(flop_budget=2**50, quiet=True) as b:
        out = fn()
    try:
        ns = b.summary_dict(by_namespace=True).get("by_namespace") or {}
        ops = sum(float(v.get("calls", 0.0)) for v in ns.values())
    except Exception as e:
        ops = str(e)
    print(f"{name:45s} flops={int(b.flops_used):>12d} ops={ops} shape={getattr(out,'shape',None)}")
rng = np.random.default_rng(0)
p, m = 6, 10
A = fnp.asarray(rng.standard_normal((p, m)).astype(np.float32))
v = fnp.asarray(rng.standard_normal(m).astype(np.float32))
bill("sum axis=1 (6,10)", lambda: A.sum(axis=1))
bill("sum axis=0 (6,10)", lambda: A.sum(axis=0))
bill("sum all (6,10)", lambda: A.sum())
bill("fnp.sum axis=1", lambda: fnp.sum(A, axis=1))
bill("A*A", lambda: A*A)
bill("A*2.0", lambda: A*2.0)
bill("A*v[None,:]", lambda: A*v[None,:])
bill("sqrt(v)", lambda: fnp.sqrt(v))
bill("tanh(v)", lambda: fnp.tanh(v))
bill("isfinite(A)", lambda: fnp.isfinite(A))
bill("where(isfinite(A),A,0)", lambda: fnp.where(fnp.isfinite(A), A, np.float32(0.0)))
bill("where(cond, A, 0) only", (lambda c=fnp.isfinite(A) if False else None: None))
bill("maximum(v, 1e-12)", lambda: fnp.maximum(v, np.float32(1e-12)))
bill("clip(v,-40,40)", lambda: fnp.clip(v, np.float32(-40), np.float32(40)))
bill("argsort(v) m=10", lambda: fnp.argsort(v))
v1024 = fnp.asarray(rng.standard_normal(1024).astype(np.float32))
bill("argsort(1024)", lambda: fnp.argsort(v1024))
Q = fnp.asarray(rng.standard_normal((40, 8)).astype(np.float32))
bill("qr (40,8)", lambda: fnp.linalg.qr(Q))
Q2 = fnp.asarray(rng.standard_normal((1024, 256)).astype(np.float32))
bill("qr (1024,256)", lambda: fnp.linalg.qr(Q2))
Q3 = fnp.asarray(rng.standard_normal((1024, 4)).astype(np.float32))
bill("qr (1024,4)", lambda: fnp.linalg.qr(Q3))
bill("pad (6,10)->(7,10)", lambda: fnp.pad(A, ((0,1),(0,0))))
bill("diag(v) 10", lambda: fnp.diag(v))
bill("diagonal(A sq)", lambda: fnp.diagonal(fnp.asarray(np.eye(5,dtype=np.float32))))
bill("eye(10)", lambda: fnp.eye(10, dtype=fnp.float32))
bill("ones((10,10))", lambda: fnp.ones((10,10), dtype=fnp.float32))
bill("zeros((10,10))", lambda: fnp.zeros((10,10), dtype=fnp.float32))
bill("ones - eye", lambda: fnp.ones((10,10), dtype=fnp.float32) - fnp.eye(10, dtype=fnp.float32))
bill("stack 3 x (10,)", lambda: fnp.stack([v,v,v]))
bill("concat 2 x (6,10) ax1", lambda: fnp.concatenate([A,A],axis=1))
bill("reshape (6,10)->(60,)", lambda: fnp.reshape(A,(60,)))
bill("A.reshape method", lambda: A.reshape((60,)))
bill("A.T", lambda: A.T)
bill("A.transpose(1,0)", lambda: A.transpose(1,0))
bill("astype f64", lambda: A.astype(fnp.float64))
bill("take axis1", lambda: fnp.take(A, fnp.asarray(np.array([1,2,3])), axis=1))
bill("fancy A[:, idx]", lambda: A[:, fnp.asarray(np.array([1,2,3]))])
bill("A>=0", lambda: A >= np.float32(0))
bill("norm.cdf(v)", lambda: flops.stats.norm.cdf(v))
bill("norm.pdf(v)", lambda: flops.stats.norm.pdf(v))
