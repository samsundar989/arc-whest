import numpy as np
import flopscope as flops, flopscope.numpy as fnp
from flopscope._flops import einsum_cost
def bill(name, fn):
    with flops.BudgetContext(flop_budget=2**50, quiet=True) as b:
        out = fn()
    print(f"{name:45s} flops={int(b.flops_used):>12d} shape={getattr(out,'shape',None)}")
rng=np.random.default_rng(0)
t,n=5,7
M=fnp.asarray(rng.standard_normal((t,n,n)).astype(np.float32))
L=fnp.asarray(rng.standard_normal((t,n)).astype(np.float32))
R=fnp.asarray(rng.standard_normal((t,n)).astype(np.float32))
c=fnp.asarray(rng.standard_normal((t,)).astype(np.float32))
bill("einsum tij,ti,tj->ij", lambda: fnp.einsum("tij,ti,tj->ij", M, L, R))
print("einsum_cost", einsum_cost("tij,ti,tj->ij", [(t,n,n),(t,n),(t,n)]))
bill("einsum ti,ti,t->i", lambda: fnp.einsum("ti,ti,t->i", L, R, c))
print("einsum_cost", einsum_cost("ti,ti,t->i", [(t,n),(t,n),(t,)]))
print("big", einsum_cost("tij,ti,tj->ij", [(27,1024,1024),(27,1024),(27,1024)]))
A64 = fnp.asarray(rng.standard_normal((6,10)))
bill("astype f64->f32", lambda: A64.astype(fnp.float32))
A = fnp.asarray(rng.standard_normal((6,10)).astype(np.float32))
bill("A * np.float64(2)", lambda: A*np.float64(2.0))
bill("A * np.float32(2)", lambda: A*np.float32(2.0))
i64 = fnp.argsort(fnp.asarray(rng.standard_normal(10).astype(np.float32)))
bill("argsort(int64)", lambda: fnp.argsort(i64))
bill("i64 >= 3", lambda: i64 >= 3)
bill("i64 - 3", lambda: i64 - 3)
bill("where(i64>=3, i64-3, 7)", lambda: fnp.where(i64 >= 3, i64 - 3, 7))
bill("where(i64>=3, 1.0f, 0.0f)", lambda: fnp.where(i64 >= 3, np.float32(1.0), np.float32(0.0)))
bill("asarray list f32", lambda: fnp.asarray([1.0]*10, dtype=fnp.float32))
bill("fnp.array nested", lambda: fnp.array([[1.0,2.0],[3.0,4.0]], dtype=fnp.float32))
bill("stack w0 keys 3x(10,)", lambda: fnp.stack([A[0],A[1],A[2]]))
bill("mean", lambda: A[0].mean())
bill("ones_like(v)", lambda: fnp.ones_like(A[0]))
bill("eye(10) f32", lambda: fnp.eye(10, dtype=fnp.float32))
bill("diag(vec)", lambda: fnp.diag(A[0]))
bill("X[:, intidx] fancy", lambda: A[:, [0,1,2]])
idx = fnp.asarray(np.array([0,1,2]))
bill("X[:, fa idx] fancy", lambda: A[:, idx])
bill("sum(axis=2) (2,3,4)", lambda: fnp.asarray(rng.standard_normal((2,3,4)).astype(np.float32)).sum(axis=2))
bill("maximum(v, f64 scalar) on f64", lambda: fnp.maximum(A64, fnp.float64(0.0)))
bill("isfinite f64", lambda: fnp.isfinite(A64))
bill("where(isfinite f64)", lambda: fnp.where(fnp.isfinite(A64), A64, fnp.float64(0.0)))
