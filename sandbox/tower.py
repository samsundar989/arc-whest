"""
Full-tensor first-order cumulant tower for ReLU nets (sandbox, n <= 256 for kappa3, n <= 64 for kappa4).

State at pre-activation z_l: mu (n), C (n x n), K3 = list of n^3 tensors (one per birth layer, index = birth layer),
K4 = single n^4 tensor or None.
"""
import numpy as np
from relu_hermite import *

def make_net(n, L, seed, scale=2.0):
    rng = np.random.default_rng(seed)
    return [rng.standard_normal((n, n))*np.sqrt(scale/n) for _ in range(L)]

def mode3(K, W):
    """K x_1 W x_2 W x_3 W"""
    n = W.shape[0]
    K = np.tensordot(W, K, axes=([1], [0]))            # a j k
    K = np.tensordot(W, K, axes=([1], [1])).transpose(1, 0, 2)   # b a k -> a b k
    K = np.tensordot(W, K, axes=([1], [2])).transpose(1, 2, 0)   # c a b -> a b c
    return np.ascontiguousarray(K)

def mode4(K, W):
    K = np.tensordot(W, K, axes=([1], [0]))                                  # a j k l
    K = np.tensordot(W, K, axes=([1], [1])).transpose(1, 0, 2, 3)           # a b k l
    K = np.tensordot(W, K, axes=([1], [2])).transpose(1, 2, 0, 3)           # a b c l
    K = np.tensordot(W, K, axes=([1], [3])).transpose(1, 2, 3, 0)           # a b c d
    return np.ascontiguousarray(K)

def sym_mC(m, C):
    """Sym(m (x) C)_{ijk} = (m_i C_jk + m_j C_ik + m_k C_ij)/3"""
    return (m[:, None, None]*C[None, :, :] + m[None, :, None]*C[:, None, :] + m[None, None, :]*C[:, :, None])/3.0

def sym_CC(C):
    """Sym(C (x) C)_{ijkl} = (C_ij C_kl + C_ik C_jl + C_il C_jk)/3"""
    return (np.einsum('ij,kl->ijkl', C, C) + np.einsum('ik,jl->ijkl', C, C) + np.einsum('il,jk->ijkl', C, C))/3.0

def k3_parts(K):
    n = K.shape[0]; idx = np.arange(n)
    d = K[idx, idx, idx].copy()
    P = K[idx, idx, :].copy(); np.fill_diagonal(P, 0.0)   # P[i,k] = K_iik
    return d, P

def k4_parts(K):
    n = K.shape[0]; idx = np.arange(n)
    d = K[idx, idx, idx, idx].copy()
    K22 = K[idx, idx][:, idx, idx].copy(); np.fill_diagonal(K22, 0.0)     # K_iijj
    K31 = K[idx, idx, idx, :].copy(); np.fill_diagonal(K31, 0.0)          # K_iiij
    return d, K22, K31

def set_pair(K, P, d):
    """overwrite pair entries (i,i,k),(i,k,i),(k,i,i) of K with P[i,k] (i!=k) and diagonal with d (in place)."""
    n = K.shape[0]; idx = np.arange(n)
    K[idx, idx, :] = P; K[idx, :, idx] = P; K[:, idx, idx] = P.T
    K[idx, idx, idx] = d

def transport_k3(K, mu, sigma, mode):
    """first-order transport of kappa3(z) through ReLU."""
    g, T2, X2, T3, Y2 = transport_factors(mu, sigma)
    d, P = k3_parts(K)
    Kh = K*g[:, None, None]*g[None, :, None]*g[None, None, :]
    if mode == 'gate':
        return Kh
    newP = T2[:, None]*g[None, :]*P + X2[:, None]*Y2[None, :]*P.T
    np.fill_diagonal(newP, 0.0)
    set_pair(Kh, newP, T3*d)
    return Kh

def transport_k4(K, mu, sigma, mode):
    g, T2, X2, T3, Y2 = transport_factors(mu, sigma)
    Kh = K*g[:, None, None, None]*g[None, :, None, None]*g[None, None, :, None]*g[None, None, None, :]
    if mode == 'gate':
        return Kh
    n = K.shape[0]; idx = np.arange(n)
    d, K22, K31 = k4_parts(K)
    m, V, k3h, _ = relu_moments(mu, sigma)
    B = coefB(mu, sigma, 4); A = coefA(mu, sigma, 4); C = coefC(mu, sigma, 4)
    a = mu/sigma; p = phi(a)
    Ed = lambda k: sigma**(-k-1)*He(k, -a)*p
    D4 = sigma**4*(24*Phi(a) - 24*m*Ed(0) + 12*m*m*Ed(1) - 4*m**3*Ed(2))
    T4 = (D4 - 4*k3h*A[4] - 6*V*B[4])/(24*sigma**4)
    U = B[3]/(6*sigma**3); Xb = B[1]/sigma
    T31 = C[3]/(6*sigma**3)
    new22 = T2[:, None]*T2[None, :]*K22 + U[:, None]*Xb[None, :]*K31 + Xb[:, None]*U[None, :]*K31.T
    np.fill_diagonal(new22, 0.0)
    new31 = T31[:, None]*g[None, :]*K31; np.fill_diagonal(new31, 0.0)
    # (i,i,j,k) entries: factor T2_i g_j g_k instead of g_i^2 g_j g_k
    I3, J3, K3_ = hub_square_positions(n)
    fac = (T2/g**2)[I3]
    for pos in [(I3, I3, J3, K3_), (I3, J3, I3, K3_), (I3, J3, K3_, I3), (J3, I3, I3, K3_), (J3, I3, K3_, I3), (J3, K3_, I3, I3)]:
        Kh[pos] = Kh[pos]*fac
    # write patterns: (i,i,j,j) in 3 index placements (symmetric), (i,i,i,j) in 4 placements
    I, J = np.meshgrid(idx, idx, indexing='ij')
    Kh[I, I, J, J] = new22; Kh[I, J, I, J] = new22; Kh[I, J, J, I] = new22
    Kh[I, I, I, J] = new31; Kh[I, I, J, I] = new31; Kh[I, J, I, I] = new31; Kh[J, I, I, I] = new31
    Kh[idx, idx, idx, idx] = T4*d
    return Kh

def k4_to_k3_born(mu, sigma, d4, K22, K31, K4=None):
    """first-order kappa3(h) generated by kappa4(z) patterns (zero-correlation responses)."""
    n = len(mu); idx = np.arange(n)
    g, T2, X2, T3, Y2 = transport_factors(mu, sigma)
    a = mu/sigma; p = phi(a)
    m, V, _, _ = relu_moments(mu, sigma)
    B = coefB(mu, sigma, 4); A = coefA(mu, sigma, 4); C = coefC(mu, sigma, 4)
    # pair (i,i,j): 1/2 T2_i (phi_j/sigma_j) K22_ij + (1/6) B3_i g_j K31_ij/sigma_i^3 - (1/6)(B1_i/sigma_i) alpha_j phi_j K31_ji/sigma_j^2
    P = 0.5*T2[:, None]*Y2[None, :]*K22 + (B[3]/(6*sigma**3))[:, None]*g[None, :]*K31 \
        - (B[1]/(6*sigma))[:, None]*(a*p/sigma**2)[None, :]*K31.T
    np.fill_diagonal(P, 0.0)
    dd = (C[4] - 3*V*A[4])/(24*sigma**4)*d4
    K = np.zeros((n, n, n))
    if K4 is not None:
        # distinct (i,j,k): 1/2 [Y2_i g_j g_k K4_iijk + Y2_j g_i g_k K4_jjik + Y2_k g_i g_j K4_kkij]
        Q = K4[idx, idx]                        # Q[i,j,k] = K4[i,i,j,k]
        K = 0.5*(Y2[:, None, None]*g[None, :, None]*g[None, None, :]*Q
                 + Y2[None, :, None]*g[:, None, None]*g[None, None, :]*Q.transpose(1, 0, 2)
                 + Y2[None, None, :]*g[:, None, None]*g[None, :, None]*Q.transpose(2, 0, 1))
    set_pair(K, P, dd)
    return K

def hub_square_positions(n):
    idx = np.arange(n)
    I, J, K_ = np.meshgrid(idx, idx, idx, indexing='ij')
    msk = (J != K_) & (J != I) & (K_ != I)
    return I[msk], J[msk], K_[msk]

def k3_to_k4_patterns(mu, sigma, d3, P3):
    """first-order kappa4(h) generated by kappa3(z): pair (i,i,j,j): 2 X2_i T2_j k3z_ijj + 2 T2_i X2_j k3z_iij ;
    diag: T43 * k3z_iii with T43 = (D_3 - 4 k3h A_3 - 6 V B_3)/(6 sigma^3), D_3 = E[(dh)^4 He_3]."""
    g, T2, X2, T3, Y2 = transport_factors(mu, sigma)
    a = mu/sigma; p = phi(a); Pa = Phi(a)
    m, V, k3h, _ = relu_moments(mu, sigma)
    A = coefA(mu, sigma, 3); B = coefB(mu, sigma, 3)
    Ed = lambda k: sigma**(-k-1)*He(k, -a)*p
    D3 = sigma**3*(24*m*(1-Pa) + 12*m*m*Ed(0) - 4*m**3*Ed(1))
    T43 = (D3 - 4*k3h*A[3] - 6*V*B[3])/(6*sigma**3)
    K22 = 2*X2[:, None]*T2[None, :]*P3.T + 2*T2[:, None]*X2[None, :]*P3      # P3[i,j] = k3z_iij ; P3.T[i,j] = k3z_ijj
    np.fill_diagonal(K22, 0.0)
    return T43*d3, K22

def born_k4_full(mu, sigma, rho, pmax, hub_square=True):
    n = len(mu); idx = np.arange(n)
    k4, K22, K31 = born_kappa4_patterns(mu, sigma, rho, pmax)
    K = np.zeros((n, n, n, n))
    if hub_square:
        # kappa4_{iijk} (j,k,i distinct) at O(rho^2): (B_2(i) - 2 A_1(i)^2) A_1(j) A_1(k) rho_ij rho_ik
        A = coefA(mu, sigma, 2); B = coefB(mu, sigma, 2)
        rt = rho.copy(); np.fill_diagonal(rt, 0.0)
        X = B[2] - 2*A[1]**2
        T = np.einsum('i,j,k,ij,ik->ijk', X, A[1], A[1], rt, rt)
        I3, J3, K3_ = hub_square_positions(n)
        vals = T[I3, J3, K3_]
        for pos in [(I3, I3, J3, K3_), (I3, J3, I3, K3_), (I3, J3, K3_, I3), (J3, I3, I3, K3_), (J3, I3, K3_, I3), (J3, K3_, I3, I3)]:
            K[pos] = vals
    I, J = np.meshgrid(idx, idx, indexing='ij')
    K[I, I, J, J] = K22; K[I, J, I, J] = K22; K[I, J, J, I] = K22
    K[I, I, I, J] = K31; K[I, I, J, I] = K31; K[I, J, I, I] = K31; K[J, I, I, I] = K31
    K[idx, idx, idx, idx] = k4
    return K

DEFAULT = dict(k3=True, k4=False, transport='exact', born_distinct=True, distinct_maxorder=6,
               born_pair=True, born_diag=True, indirect_mean=True, indirect_cov=True,
               indirect_max_age=None, direct_max_age=None, pmax=40, readout_k33=True,
               sphere=False, k4_born=True, k4_to_k3=True, record=True, template_eps=None,
               k4face=False, face_gate='T2', template_eps4=None, proj=True, face_lam=None, final_scale=None,
               merge_births=False, template_mode='born', k4mode='full', k3_to_k4=True)

def run_tower(W, opts=None, x_cov_scale=1.0):
    """W: list of L matrices. Returns dict with prediction y and per-layer records."""
    o = dict(DEFAULT); o.update(opts or {})
    L = len(W); n = W[0].shape[0]
    mu = np.zeros(n); C = x_cov_scale*W[0]@W[0].T
    K3 = {}     # birth layer -> tensor at current z
    K4 = None
    if o['sphere'] and o['k4']:
        K4 = -(2.0/(n+2))*3.0*sym_CC(C)
    q4 = np.zeros(n); P4 = 0.0          # scalar-channel kappa4 carrier (k4mode='scalar')
    Ctil = None; lam = 0.0
    if o['k4face']:
        Ctil = C.copy(); lam = -6.0/(n+2) if o['sphere'] else 0.0
        if o['face_lam'] is not None:
            lam = o['face_lam']
    rec = []
    for l in range(1, L+1):      # z_l is current
        sigma = np.sqrt(np.diag(C)); alpha = mu/sigma
        rho = C/np.outer(sigma, sigma)
        # incoming cumulant diagonals / pairs
        n_ = n
        d3 = np.zeros(n); P3 = np.zeros((n, n)); d3_all = np.zeros(n)
        for b, K in K3.items():
            d, P = k3_parts(K); d3_all += d
            if o['indirect_max_age'] is None or (l - b) <= o['indirect_max_age']:
                d3 += d; P3 += P
        if K4 is not None:
            d4, K22, K31 = k4_parts(K4)
        else:
            d4 = np.zeros(n); K22 = np.zeros((n, n)); K31 = np.zeros((n, n))
        if o['k4mode'] == 'scalar':
            d4 = d4 + q4
            K22s = P4*np.ones((n, n)); np.fill_diagonal(K22s, 0.0); K22 = K22 + K22s
        if Ctil is not None:
            vt = np.diag(Ctil)
            d4 = d4 + lam*vt**2
            K22f = lam*(np.outer(vt, vt) + 2*Ctil**2)/3.0; np.fill_diagonal(K22f, 0.0); K22 = K22 + K22f
            K31f = lam*vt[:, None]*Ctil; np.fill_diagonal(K31f, 0.0); K31 = K31 + K31f
        c3, c4, v3, v4 = shift_coefs(mu, sigma)
        D3dir = np.zeros(n)
        for b, K in K3.items():
            if o['direct_max_age'] is None or (l - b) <= o['direct_max_age']:
                D3dir += k3_parts(K)[0]
        y = sigma*phi(alpha) + mu*Phi(alpha) + c3*D3dir/sigma**2 + c4*d4/sigma**3
        if o['readout_k33']:
            y = y + readout_c33(alpha)*D3dir**2/sigma**5
        if o['record']:
            r_ = dict(mu=mu.copy(), C=C.copy(), d3=d3_all.copy(), d4=d4.copy(), y=y.copy(),
                      d3_by_birth={b: k3_parts(K)[0] for b, K in K3.items()},
                      P3=sum((k3_parts(K)[1] for K in K3.values()), np.zeros((n, n))),
                      P3_by_birth={b: k3_parts(K)[1] for b, K in K3.items()},
                      K22=K22.copy(), K31=K31.copy())
            if o['proj'] and len(K3) > 0:
                S = sym_mC(mu, C); SS = np.sum(S*S)
                Ktot = sum(K3.values())
                r_['proj3'] = dict(eps_all=float(np.sum(Ktot*S)/SS), cos2_all=float(np.sum(Ktot*S)**2/(SS*np.sum(Ktot*Ktot))),
                                   eps_by_birth={b: float(np.sum(K*S)/SS) for b, K in K3.items()})
            rec.append(r_)
        if l == L:
            break
        # ---- ReLU: Gaussian moments + shifts
        m0, V0, k3d, k4d = relu_moments(mu, sigma)
        Cov = cov_relu(mu, sigma, rho, o['pmax'])
        m = m0.copy()
        if o['indirect_mean']:
            m = m + c3*d3/sigma**2 + c4*d4/sigma**3
        if o['indirect_cov']:
            p = phi(alpha); P_ = Phi(alpha)
            dCov = 0.5*(P3*np.outer(p/sigma, P_) + P3.T*np.outer(P_, p/sigma)) \
                 + 0.25*K22*np.outer(p/sigma, p/sigma) \
                 - (1.0/6.0)*(K31*np.outer(alpha*p/sigma**2, P_) + K31.T*np.outer(P_, alpha*p/sigma**2))
            np.fill_diagonal(dCov, 0.0)
            Cov = Cov + dCov + np.diag(v3*d3 + v4*d4)
        if o['record']:      # post-ReLU first/second moments actually propagated (used by x6_*.py)
            rec[-1]['m_h'] = m.copy(); rec[-1]['Cov_h'] = Cov.copy()
        # ---- kappa3 of h
        newK3 = {}
        if o['k3']:
            for b, K in K3.items():
                newK3[b] = transport_k3(K, mu, sigma, o['transport'])
            born = born_kappa3_full(mu, sigma, rho, maxorder=o['distinct_maxorder'], pmax=o['pmax'],
                                    include_distinct=o['born_distinct'], include_pair=o['born_pair'])
            if not o['born_diag']:
                idx = np.arange(n); born[idx, idx, idx] = 0.0
            if o['template_eps'] is not None:
                eps_l = o['template_eps'](l, n)
                if eps_l != 0.0:
                    born = born + eps_l*sym_mC(m0, cov_relu(mu, sigma, rho, o['pmax']))
            if (K4 is not None or Ctil is not None or o['k4mode'] == 'scalar') and o['k4_to_k3']:
                born = born + k4_to_k3_born(mu, sigma, d4, K22, K31, K4)
            newK3[l] = born
        # ---- kappa4 of h
        newK4 = None
        P3_all = sum((k3_parts(K)[1] for K in K3.values()), np.zeros((n, n)))
        if o['k4']:
            newK4 = transport_k4(K4, mu, sigma, o['transport']) if K4 is not None else np.zeros((n,)*4)
            if o['k4_born']:
                newK4 = newK4 + born_k4_full(mu, sigma, rho, o['pmax'])
            if o['k3_to_k4'] and len(K3) > 0:
                dq, K22q = k3_to_k4_patterns(mu, sigma, d3_all, P3_all)
                idx = np.arange(n); I, J = np.meshgrid(idx, idx, indexing='ij')
                newK4[I, I, J, J] += K22q; newK4[I, J, I, J] += K22q; newK4[I, J, J, I] += K22q
                newK4[idx, idx, idx, idx] += dq
        if o['merge_births'] and len(newK3) > 1:
            newK3 = {0: sum(newK3.values())}
        if o['k4mode'] == 'scalar':
            # diag: e_hat = T4 q4 + born diag ; pair: p_hat_ij = T2_i T2_j P4 + born pair b_ij
            g_, T2_, _, _, _ = transport_factors(mu, sigma)
            a_ = alpha; p_ = phi(a_)
            m_, V_, k3h_, k4h_ = relu_moments(mu, sigma)
            A_ = coefA(mu, sigma, 4); B_ = coefB(mu, sigma, 4)
            Ed_ = lambda k: sigma**(-k-1)*He(k, -a_)*p_
            D4_ = sigma**4*(24*Phi(a_) - 24*m_*Ed_(0) + 12*m_*m_*Ed_(1) - 4*m_**3*Ed_(2))
            T4_ = (D4_ - 4*k3h_*A_[4] - 6*V_*B_[4])/(24*sigma**4)
            e_hat = T4_*q4 + k4h_
            _, b22, _ = born_kappa4_patterns(mu, sigma, rho, o['pmax'])
            p_hat = np.outer(T2_, T2_)*P4 + b22; np.fill_diagonal(p_hat, 0.0)
            if o['k3_to_k4'] and len(K3) > 0:
                dq, K22q = k3_to_k4_patterns(mu, sigma, d3_all, P3_all)
                e_hat = e_hat + dq; p_hat = p_hat + K22q
            Wn_ = W[l]; W2_ = Wn_*Wn_
            q4 = (W2_*W2_)@e_hat + 3*np.sum(W2_*(W2_@p_hat), axis=1)        # exact diagonal (1 matmul)
            P4 = (4.0/n**2)*(np.sum(e_hat) + np.sum(p_hat))                 # mean-field pair level
        # ---- linear layer
        Wn = W[l]
        if Ctil is not None:
            g_, T2_, _, _, _ = transport_factors(mu, sigma)
            tf = np.sqrt(T2_) if o['face_gate'] == 'T2' else g_
            Ctil = Wn@(np.outer(tf, tf)*Ctil)@Wn.T
        mu = Wn@m; C = Wn@Cov@Wn.T
        K3 = {b: mode3(K, Wn) for b, K in newK3.items()}
        K4 = mode4(newK4, Wn) if newK4 is not None else None
    fs = o['final_scale'] if o['final_scale'] is not None else (e1_chi(n) if o['sphere'] else 1.0)
    y = y*fs
    return dict(y=y, rec=rec, mu=mu, C=C, K3=K3, K4=K4)
