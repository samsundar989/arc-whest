"""Generate `estimator_k3_v62_sig.py`: v59 plus an INERT per-layer sigma corrector.

    python tools/build_v62.py                          emit, sigma pages all zero (inert)
    python tools/build_v62.py --params <npz>           inject twin-fitted sigma pages
    python tools/build_v62.py --base <file> --out <f>  other base (e.g. a twin S1 export)

HANDOFF 2026-09-25 Step 2 stage S4 / PLAN rev 13 §3 Step 2 (v): "a second
33->32->1 page per layer outputting a multiplicative correction to var_pre".

WHY var_pre AND NOT diag(cov_out). Anatomy 2's one-step table (RESULTS.md) says
the variance CONSUMED at layer l -- the `var` that sets sigma and alpha for this
layer's Wick step -- is the largest single marginal source of one-step error. A
correction on diag(cov_out) would only reach that consumer one layer later and
through W. So the page acts right where `var` is formed, before `sigma`.

FEATURES must exist at that point, i.e. before `mu_out`. Six raw channels:
mu_pre, sigma, alpha, D3/sigma^3, ||W[:,i]||, mu_pre - mean(mu_pre); expanded as
the mean corrector's are (x, x^2, the 15 pairwise products) = 27 columns,
standardised by frozen per-layer (smu, sisd) computed by the twin at init.
`D3` is therefore computed BEFORE the covariance block instead of after it --
it reads only the carried tower, never `var`, so moving the line changes no
number (asserted by --verify-inert through the anatomy2 bit-parity harness).

    var <- var * (1 + g * (tanh(X S1 + c1) S2 + c2)),   g = _SIG_GAIN

With S2 = c2 = 0 the factor is exactly 1.0 and the file is bit-identical to its
base on every net. Cost: ~2 MFLOP and ~25 op calls per layer (+~400 ops per MLP).
"""
from __future__ import annotations

import argparse
import base64
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
NF_RAW = 6
PI = [i for i in range(NF_RAW) for j in range(i + 1, NF_RAW)]
PJ = [j for i in range(NF_RAW) for j in range(i + 1, NF_RAW)]
NF = 2 * NF_RAW + len(PI)          # 27
H = 32
DEPTH = 16
ORDER = ("smu", "sisd", "S1", "c1", "S2", "c2")
SHAPES = {"smu": (DEPTH, NF), "sisd": (DEPTH, NF), "S1": (DEPTH, NF, H), "c1": (DEPTH, H),
          "S2": (DEPTH, H, 1), "c2": (DEPTH, 1)}

_A_D3 = "    D3 = _dslice3(adv) if adv is not None else fnp.zeros(n, dtype=dtype)\n"
_A_MU = "    mu_pre = WT @ mu\n"
_A_METRIC = "    metric = float(init_scale)\n"
_A_CONST = '''                "corr": _corr_arrays(dtype)}
'''
_A_LAYER_DEF = "\ndef _layer(W, state, table, dtype, const, init_scale, last_layer, gens,\n"

_BLOCK = '''

# =========================== THE IN-LOOP SIGMA CORRECTOR (v62) ==============
# HANDOFF 2026-09-25 Step 2 stage S4, generated by `tools/build_v62.py`. A
# per-layer 27 -> 32 -> 1 tanh page that rescales the pre-activation variance
# CONSUMED at this layer, before sigma and alpha are formed. Fitted end to end
# through the chain by the differentiable twin (`tools/twin/twin.py`). With the
# output page at zero the factor is exactly 1.0 and the chain is unchanged.
_SIG_ON = True
_SIG_GAIN = 0.01
_SIG_PI = {pi}
_SIG_PJ = {pj}
_SIG_B64 = {{
{blob}}}
_SIG_DECODED = None


def _sig_decode():
    global _SIG_DECODED
    if _SIG_DECODED is None:
        _SIG_DECODED = {{
            k: (list(_array.array("f", _base64.b64decode(b))), tuple(s))
            for k, (b, s) in _SIG_B64.items()}}
    return _SIG_DECODED


def _sig_arrays(dtype):
    if not _SIG_ON or not _SIG_B64:
        return None
    return {{k: fnp.reshape(fnp.asarray(v, dtype=dtype), s)
            for k, (v, s) in _sig_decode().items()}}


def _sig_raw(mu_pre, var, D3, W, dtype):
    """The six raw channels at the point `var` is formed, `(n, 6)`."""
    sigma = fnp.sqrt(var)
    inv = fnp.divide(dtype(1.0), sigma)
    return fnp.stack([mu_pre, sigma, mu_pre * inv, D3 * (inv * inv * inv),
                      fnp.sqrt((W * W).sum(axis=0)), mu_pre - mu_pre.mean()], axis=1)


def _sig_factor(li, sig, mu_pre, var, D3, W, dtype):
    """`1 + g * page(features)`, an `(n,)` array; exactly 1.0 for a zero page."""
    if li >= sig["S1"].shape[0]:
        return dtype(1.0)
    X = _sig_raw(mu_pre, var, D3, W, dtype)
    X = fnp.concatenate([X, X * X, X[:, _SIG_PI] * X[:, _SIG_PJ]], axis=1)
    X = (X - sig["smu"][li]) * sig["sisd"][li]
    h = fnp.tanh(X @ sig["S1"][li] + sig["c1"][li])
    return (h @ sig["S2"][li] + sig["c2"][li])[:, 0] * _SIG_GAIN + dtype(1.0)
'''

_APPLY = '''    if _SIG_ON and const.get("sig") is not None:
        var = var * _sig_factor(layer_index, const["sig"], mu_pre, var, D3, W, dtype)
    metric = float(init_scale)
'''


def _enc(a):
    a = np.ascontiguousarray(a, dtype=np.float32)
    b = base64.b64encode(a.tobytes()).decode()
    lines = "".join(f'        "{b[i:i + 96]}"\n' for i in range(0, len(b), 96))
    shape = ", ".join(str(d) for d in a.shape)
    return lines, shape


def default_params():
    p = {k: np.zeros(s, dtype=np.float32) for k, s in SHAPES.items()}
    p["sisd"][:] = 1.0
    rng = np.random.default_rng(62)          # S1 random, S2 zero: inert but trainable
    p["S1"][:] = rng.normal(0, 1.0 / np.sqrt(NF), size=SHAPES["S1"]).astype(np.float32)
    return p


def build(base: Path, params: dict) -> str:
    src = base.read_text(encoding="utf-8")
    for a in (_A_D3, _A_MU, _A_METRIC, _A_CONST, _A_LAYER_DEF):
        if src.count(a) != 1:
            raise SystemExit(f"anchor count {src.count(a)} != 1:\n{a}")
    if "_SIG_ON" in src:
        raise SystemExit("base already carries a sigma corrector")
    # D3 before the covariance block (reads only the tower; numerically inert move)
    src = src.replace(_A_D3, "", 1)
    src = src.replace(_A_MU, _A_MU + _A_D3, 1)
    src = src.replace(_A_METRIC, _APPLY, 1)
    src = src.replace(_A_CONST, '''                "corr": _corr_arrays(dtype),
                "sig": _sig_arrays(dtype)}
''', 1)
    blob = ""
    for k in ORDER:
        v = np.asarray(params[k], dtype=np.float32)
        if v.shape != SHAPES[k]:
            raise SystemExit(f"{k}: {v.shape} != {SHAPES[k]}")
        lines, shape = _enc(v)
        blob += f'    "{k}": (\n{lines}    , ({shape})),\n'
    block = _BLOCK.format(pi=PI, pj=PJ, blob=blob)
    return src.replace(_A_LAYER_DEF, block + _A_LAYER_DEF, 1)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--base", default="estimator_k3_v59_corr400.py")
    ap.add_argument("--params", default="")
    ap.add_argument("--out", default="estimator_k3_v62_sig.py")
    a = ap.parse_args(argv)
    params = default_params()
    if a.params:
        params.update({k: v for k, v in np.load(a.params).items() if k in SHAPES})
    base = Path(a.base) if Path(a.base).is_absolute() else ROOT / a.base
    Path(a.out).write_text(build(base, params), encoding="utf-8", newline="\n")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
