"""Lane M2 table: G_drop, G_aug and per-family shares from m2_w*.json (floor-free MSEs)."""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
T95 = {7: 2.365, 15: 2.131}


def rel_gain(base, var):
    """pooled (mean_base - mean_var)/mean_base, plus a paired t95 on per-net differences."""
    base, var = np.asarray(base), np.asarray(var)
    d = base - var
    m = base.mean()
    se = d.std(ddof=1) / math.sqrt(len(d))
    t = T95.get(len(d) - 1, 2.0)
    return d.mean() / m, (d.mean() - t * se) / m, (d.mean() + t * se) / m, int((d > 0).sum())


def main() -> int:
    out = {}
    lines = []
    for w in (256, 512, 1024):
        p = HERE / f"m2_w{w}.json"
        if not p.exists():
            continue
        R = json.loads(p.read_text(encoding="utf-8"))
        nets = R["nets"]
        vs = [v for v in nets[0]["variants"] if "error" not in nets[0]["variants"][v]]
        get = lambda v, k: np.array([n["variants"][v][k] for n in nets])  # noqa: E731
        fin = {v: get(v, "mse_final") for v in vs}
        alll = {v: get(v, "mse_all") for v in vs}
        layers = {v: np.mean([n["variants"][v]["mse_layers"] for n in nets], axis=0) for v in vs}
        secs = {v: float(get(v, "seconds").mean()) for v in vs}
        floor = float(np.mean([n["floor_final"] for n in nets]))
        rec = {"n_nets": len(nets), "floor_final": floor,
               "mean_mse_final": {v: float(fin[v].mean()) for v in vs},
               "mean_mse_all": {v: float(alll[v].mean()) for v in vs},
               "mean_seconds": secs,
               "d0_vs_b_maxabs": max(n.get("d0_vs_b_maxabs", 0) for n in nets)}
        g = {}
        for name, b, v in [("G_aug (a->b)", "a", "b"), ("G_drop (b->c)", "b", "c")] + \
                [(f"family {f} alone (b->d+{f})", "b", f"d+{f}") for f in
                 ("T1", "E3", "E21a", "E21b", "E")] + [("d0 vs b", "b", "d0")]:
            if b in fin and v in fin:
                gf = rel_gain(fin[b], fin[v])
                ga = rel_gain(alll[b], alll[v])
                g[name] = {"final": gf, "all_layers": ga}
        rec["gains"] = g
        rec["per_layer_rel_c_vs_b"] = ((layers["b"] - layers["c"]) / layers["b"]).tolist()
        out[w] = rec
        lines.append(f"\n## n = {w}  ({len(nets)} nets, depth {R['depth']}, {R['dtype']}; "
                     f"label floor {floor:.2e}, subtracted)\n")
        lines.append("| variant | final MSE | all-layer MSE | s/net |")
        lines.append("|---|---|---|---|")
        for v in vs:
            lines.append(f"| {v} | {fin[v].mean():.4e} | {alll[v].mean():.4e} | {secs[v]:.2f} |")
        lines.append("\n| quantity | final layer: gain [t95] wins | all layers: gain [t95] |")
        lines.append("|---|---|---|")
        for name, d in g.items():
            f, a = d["final"], d["all_layers"]
            lines.append(f"| {name} | {f[0]*100:+.1f}% [{f[1]*100:+.1f}, {f[2]*100:+.1f}] "
                         f"{f[3]}/{len(nets)} | {a[0]*100:+.1f}% [{a[1]*100:+.1f}, {a[2]*100:+.1f}] |")
        lines.append("\nper-layer (MSE_b − MSE_c)/MSE_b, layers 1..16: " +
                     " ".join(f"{x*100:+.0f}" for x in rec["per_layer_rel_c_vs_b"]))
    txt = "\n".join(lines)
    print(txt)
    (HERE / "m2_table.md").write_text("# Lane M2 variant table (generated by analyze_m2.py)\n" + txt + "\n",
                                      encoding="utf-8")
    (HERE / "m2_summary.json").write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
