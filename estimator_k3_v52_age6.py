def _shared_rank(n):
    r = min(int(_SHARED_RANK), n)
    return r if (r < n or _SHARED_FORCE) else 0


def _full_legs(tw):
    """`(A_L, M)` over ALL lineages, oldest first -- old legs formed from `Q`."""
    if not tw.ko:
        return tw.A_L, tw.M
    if tw._legs is None:
        tw._legs = (fnp.concatenate([_mm(tw.Q, tw.FA), tw.A_L], axis=1),
                    fnp.concatenate([_mm(tw.Q, tw.FM), tw.M], axis=1))
    return tw._legs


def _shared_contract(tw, LA, LP, A_L, M):
    """`LA A_L^T + LP M^T`, old lineages through `Q`; records the joiner's weights."""
    n = LA.shape[0]
    c = tw.ko * n
    if _SHARED_ON and _shared_rank(n) and (tw.k - tw.ko) >= _SHARED_AGE:
        tw._wts = ((LA[:, c:c + n] * LA[:, c:c + n]).sum(axis=0),
                   (LP[:, c:c + n] * LP[:, c:c + n]).sum(axis=0))
    if not tw.ko:
        return _mm(LA, A_L.T) + _mm(LP, M.T)
    old = _mm(_mm(LA[:, :c], tw.FA.T) + _mm(LP[:, :c], tw.FM.T), tw.Q.T)
    return old + _mm(LA[:, c:], tw.A_L.T) + _mm(LP[:, c:], tw.M.T)


def _carry_shared(dst, src, Q):
    dst.Q, dst.FA, dst.FM, dst.ko, dst.Sg = Q, src.FA, src.FM, src.ko, src.Sg
    dst._qU, dst._qold = src._qU, src._qold
    return dst


def _shared_join(tw):
    """Move the oldest RECENT lineage into the shared basis, if it has aged out."""
    n = tw.A_L.shape[0]
    r = _shared_rank(n)
    if not r or (tw.k - tw.ko) < _SHARED_AGE or tw._wts is None:
        return tw
    Aj = tw.A_L[:, :n]
    Mj = tw.M[:, :n]
    dA, dM = tw._wts
    if tw.ko:
        Om = tw.Q
    else:
        X = fnp.concatenate([Aj * fnp.sqrt(dA), Mj * fnp.sqrt(dM)], axis=1)
        Om = X[:, fnp.argsort((X * X).sum(axis=0))[-r:]]
    for _p in range(int(_SHARED_PASSES)):
        Y = (_mm(Aj, (_mm(Aj.T, Om)) * dA[:, None])
             + _mm(Mj, (_mm(Mj.T, Om)) * dM[:, None]))
        if tw.ko:
            Y = Y + tw.Q @ (tw.Sg @ (tw.Q.T @ Om))
        Om, _ = fnp.linalg.qr(Y)
    Qn = Om
    FAj = _mm(Qn.T, Aj)
    FMj = _mm(Qn.T, Mj)
    Sj = _mm(FAj * dA, FAj.T) + _mm(FMj * dM, FMj.T)
    if tw.ko:
        T = Qn.T @ tw.Q
        FA = fnp.concatenate([T @ tw.FA, FAj], axis=1)
        FM = fnp.concatenate([T @ tw.FM, FMj], axis=1)
        Sg = (T @ tw.Sg) @ T.T + Sj
    else:
        FA, FM, Sg = FAj, FMj, Sj
    out = _Tower(tw.A_D, tw.A_L[:, n:], tw.M[:, n:], tw.w2b, tw.k,
                 tw.Z, tw.L, tw.sb, tw.eb)
    out.Y, out.CA, out.CB = tw.Y, tw.CA, tw.CB
    if tw.F is not None:
        out.F, out.R3, out.R4, out.w3b = tw.F, tw.R3, tw.R4, tw.w3b
    out.Q, out.FA, out.FM, out.ko, out.Sg = Qn, FA, FM, tw.ko + 1, Sg
    return out


def _full_legs_lean(tw):
    """LEAN: both old legs formed by ONE product, `Q @ [FA | FM]`."""
    if not tw.ko:
        return tw.A_L, tw.M
    if tw._legs is None:
        c = tw.FA.shape[1]
        F = _mm(tw.Q, fnp.concatenate([tw.FA, tw.FM], axis=1))
        tw._legs = (fnp.concatenate([F[:, :c], tw.A_L], axis=1),
                    fnp.concatenate([F[:, c:], tw.M], axis=1))
    return tw._legs


def _shared_contract_lean(tw, LA, LP, A_L, M):
    """LEAN: `[LA | LP] @ [A | M]^T` as ONE product per part (old via Q, recent exact)."""
    n = LA.shape[0]
    c = tw.ko * n
    if _SHARED_ON and _shared_rank(n) and (tw.k - tw.ko) >= _SHARED_AGE:
        tw._wts = ((LA[:, c:c + n] * LA[:, c:c + n]).sum(axis=0),
                   (LP[:, c:c + n] * LP[:, c:c + n]).sum(axis=0))
        # QUERY BASIS: the joiner's own frozen left factors, kept as VIEWS of
        # arrays this layer already holds. No product, no copy.
        tw._qU = (LA[:, c:c + n], LP[:, c:c + n])
    rec = _mm(fnp.concatenate([LA[:, c:], LP[:, c:]], axis=1),
              fnp.concatenate([tw.A_L if tw.ko else A_L, tw.M if tw.ko else M], axis=1).T)
    if not tw.ko:
        return rec
    FF = fnp.concatenate([tw.FA, tw.FM], axis=1)
    # QUERY BASIS: `X_old` is this product's inner half -- the OLD lineages'
    # actual contribution to the consumed contraction in the current layer's
    # coordinates. It is stashed, not recomputed: the join reads it instead of
    # a carried Gram of stale weights.
    Xold = _mm(fnp.concatenate([LA[:, :c], LP[:, :c]], axis=1), FF.T)
    tw._qold = Xold
    old = _mm(Xold, tw.Q.T)
    return old + rec


def _shared_join_lean(tw):
    """LEAN join: the range finder's four leg products fused into two."""
    n = tw.A_L.shape[0]
    r = _shared_rank(n)
    if not r or (tw.k - tw.ko) < _SHARED_AGE or tw._wts is None:
        return tw
    if _QUERY_BASIS and tw._qU is None:
        return tw
    J = fnp.concatenate([tw.A_L[:, :n], tw.M[:, :n]], axis=1)
    dA, dM = tw._wts
    dJ = fnp.concatenate([dA, dM])
    if _SHARED_WEIGHTS == "sqrt":
        dJ = fnp.sqrt(dJ)
    elif _SHARED_WEIGHTS == "unif":
        dJ = dJ * 0.0 + 1.0
    if tw.ko:
        Om = tw.Q
    else:
        X = J * fnp.sqrt(dJ)
        Om = X[:, fnp.argsort((X * X).sum(axis=0))[-r:]]
    if _QUERY_BASIS:
        # ---- the CONSUMED-QUERY range finder ---------------------------- #
        # ONE power iteration of the query's own Gram,
        #     Y = E^T (E Om),   E = X_old Q_old^T + U_j J_j^T,
        # with E never formed. A SINGLE application `E^T Om` is not enough and
        # this is not a tuning choice: the sketch `Om` is deterministic (the
        # norm-selected columns, unchanged from the base, because hard rule 2
        # forbids sampling and equivariance forbids a fixed weight slice), and a
        # deterministic sketch applied once has no singular-value decay working
        # for it. The live Gram objective is ALREADY a power iteration --
        # `J D J^T Om` is `(J sqrt D)(J sqrt D)^T Om` -- so a single application
        # here would have compared two different algorithms and called the
        # difference an objective. Check (c) of `s10_parity.py` measured exactly
        # that and refused the first spelling: rank-2 query error 0.2174 against
        # the surrogate's 0.0622. Priced in the header; metered on the file.
        UA, UP = tw._qU
        U = fnp.concatenate([UA, UP], axis=1)
        rq = r - int(_QB_D3) if _QB_D3 else r
        for _p in range(int(_SHARED_PASSES)):
            Z = _mm(U, _mm(J.T, Om))
            if tw.ko and tw._qold is not None:
                Z = Z + _mm(tw._qold, _mm(tw.Q.T, Om))
            Y = _mm(J, _mm(U.T, Z))
            if tw.ko and tw._qold is not None:
                Y = Y + _mm(tw.Q, _mm(tw._qold.T, Z))
            if _QB_D3:
                # PREREGISTERED D3 protection: `_dslice3` reads the legs
                # elementwise, so `rq` columns go to the (2,1) query's range
                # and `_QB_D3` to the range of the joiner's own D3 summand.
                # The TOTAL rank is unchanged, so the compare stays fixed-rank.
                G = (tw.A_L[:, :n] * tw.M[:, :n]) * tw.w2b[:n]
                Yd = _mm(G, _mm(G.T, Om[:, :int(_QB_D3)]))
                Y = fnp.concatenate([Y[:, :rq], Yd], axis=1)
            Om, _ = fnp.linalg.qr(Y)
        Qn = Om
        FJ = _mm(Qn.T, J)
        Sj = None
    else:
        for _p in range(int(_SHARED_PASSES)):
            Y = _mm(J, (_mm(J.T, Om)) * dJ[:, None])
            if tw.ko:
                Y = Y + tw.Q @ (tw.Sg @ (tw.Q.T @ Om))
            Om, _ = fnp.linalg.qr(Y)
        Qn = Om
        FJ = _mm(Qn.T, J)
        Sj = _mm(FJ * dJ, FJ.T)
    if tw.ko:
        T = Qn.T @ tw.Q
        c = tw.FA.shape[1]
        FF = T @ fnp.concatenate([tw.FA, tw.FM], axis=1)
        FA = fnp.concatenate([FF[:, :c], FJ[:, :n]], axis=1)
        FM = fnp.concatenate([FF[:, c:], FJ[:, n:]], axis=1)
        # The carried Gram exists ONLY for the diagonal surrogate's memory of
        # older lineages. The query basis remembers them exactly through
        # `X_old`, so it is not formed and not carried.
        Sg = None if _QUERY_BASIS else (T @ tw.Sg) @ T.T + Sj
    else:
        FA, FM, Sg = FJ[:, :n], FJ[:, n:], Sj
    out = _Tower(tw.A_D, tw.A_L[:, n:], tw.M[:, n:], tw.w2b, tw.k,
                 tw.Z, tw.L, tw.sb, tw.eb)
    out.Y, out.CA, out.CB = tw.Y, tw.CA, tw.CB
    if tw.F is not None:
        out.F, out.R3, out.R4, out.w3b = tw.F, tw.R3, tw.R4, tw.w3b
    out.Q, out.FA, out.FM, out.ko, out.Sg = Qn, FA, FM, tw.ko + 1, Sg
    return out


def _proj_coef_d4_r2(n):
    """`harmonic.proj_coef(n, 4, 2)[2]`, evaluated so a width change cannot
    silently invalidate it. Verified against upstream at n = 4..4096.

    **THE SINGULARITY AT `n = 2`, and it killed two submissions.**
    `c = 1 + n/2`, and the rising factorial below is `(1 - c)(2 - c)`, which is
    EXACTLY ZERO at `c = 2`, i.e. at `n = 2`. The verification range in the line
    above starts at `4`; the hole is at `2`, so the check could never see it.

    Submissions `329887` and `329890` both died in the grading server's smoke
    test with `ESTIMATOR_EXCEPTION` after ~`95 ms`, and this is why:
    `ZeroDivisionError: float division by zero`, raised from `_layer` on the
    first layer of a width-`2` MLP. `whest validate` runs at width `4` and passes;
    `estimator.py` v2.6.1 survives width `2` because its K2 machinery never
    reaches this coefficient.

    **There is no "right answer" to compute here: UPSTREAM ITSELF RAISES.**
    `harmonic.proj_coef(2, 4, 2)` is `ZeroDivisionError` in
    `mlp_cumulant_propagation` too (checked 2026-09-05, rev `93d091a4`), so the
    degree-4 harmonic projection is genuinely undefined at width `2` rather than
    merely awkward to evaluate. Any value here is a CHOICE, and the choice made
    is to drop the term: return `0.0`, which runs the flow without its degree-4
    projection correction at a width where that projection is degenerate.

    This is a deliberate divergence from upstream at exactly one width, it is
    documented rather than silent, and it affects no graded shape -- Phase 2 is
    `1024 x 16`. What it buys is that a smoke test on a degenerate MLP cannot
    zero a hundred networks.
    """
    d, r, j = 4, 2, 2
    c = d - r + n / 2.0 - 1
    rising = 1.0
    for m in range(j):
        rising *= (1 - c + m)
    if rising == 0.0 or c == 0.0:
        return 0.0
    return ((-1.0) ** r * (c - r) / 4.0 ** j / math.factorial(r)
            / math.factorial(j - r) / c / rising)


def _get_pk_block(pK, b, d):
    """`DS_part_sum.get_block`: the pK slice a vector-partition block reads."""
    nz = tuple(i for i, x in enumerate(b) if x > 0)
    key = tuple(b[i] for i in nz)
    f = pK[tuple(sorted(key, reverse=True))]
    if len(key) == 2 and key[0] < key[1]:
        f = f.T
    if len(nz) != d:
        f = f[:, None] if nz == (0,) else f[None, :]
    return f


# ==========================================================================
# the lineage: the 2n columns born at one layer, in mode-equality form
# ==========================================================================
# Transcribed from `local_sim/p2_weff.py`, whose parity against upstream's own
# `contract_W` / `contract_wick_` / `get_dslice` is 5.6e-16 and whose spelling
# is what `local_sim/p2_k3_fnp.py::k3_flow(full=True)` runs. It is repeated here
# rather than imported because that module imports numpy and the grader sandbox
# has none; `local_sim/p2_k3_candidate_parity.py` is the standing check that the
# two spellings have not drifted apart.
#
# One lineage represents exactly
#
#     Sym( sum_j A_D[:,j] (x) M[:,j] (x) M[:,j] )              the from_dstensor block
#   + Sym( sum_j A_L[:,j] (x) 3 M[:,j] (x) C_L[:,j] )          the two-leg block
#
# with ONE shared `M`. Both blocks are born at the same layer with `M == I`, and
# every later operation applies the SAME matrix to every mode, so the equality
# survives forever. That is the whole of the saving: four (n, n) matrices where
# a dense spelling carries six, and five matmuls for the `(2,1)` slice where a
# dense spelling needs six -- the D block's `{0,1}|{2}` and `{0,2}|{1}`
# permutations are identically the same product.


class _Tower(object):
    """The WHOLE carried third-cumulant tower, as three wide blocks.

    The obvious spelling keeps a Python list of `k` lineages, each four `(n, n)`
    matrices, and issues `k` separate matmuls per operation. flopscope meters one
    OPERATION per call and Phase 2 caps residual wall time at `0.4 s` per MLP, so
    that spelling costs `~9k` operations a layer for arithmetic that is one
    matmul on a wider operand:

        [A_1 | A_2 | ... | A_k]  is  (n, k n)
        W^T [A_1 | ... | A_k]    is  ONE (n,n) @ (n, k n)

    and `sum_b X_b @ Y_b^T` is `[X_1|...|X_k] @ [Y_1|...|Y_k]^T`, again ONE
    matmul, with the sum over lineages performed by the contraction itself.

    **This is FLOP-neutral and operation-cheap.** flopscope bills `(m,k)@(k,n)`
    at `m n (2k-1)`, so `k` separate `(n,n)@(n,n)` products cost
    `k n^2 (2n-1)` and the batched `(n,n)@(n,kn)` costs `k n^2 (2n-1)` -- the
    same number. The reduction spellings differ by `n^2 (k-1)`, i.e. 0.2%, in
    the batched form's disfavour, and by a factor of `k` in its favour on the
    operation count. Measured at n=256, k=8: 8 ops -> 2 ops for `contract_W`,
    15 ops -> 3 for a summed `A @ B^T`, with the values agreeing to `6.0e-07`
    relative -- five float32 ulps of reassociation.

    Layout. `k` lineages, oldest first, each contributing `n` columns:

        A_D  (n, k n)   the from_dstensor blocks
        A_L  (n, k n)   the two-leg blocks
        w2b  (k n,)     the birth Wick vectors, so C_L = A_L * w2b (see below)
        M    (n, (k-1) n) or None -- the modes of the OLDER blocks only

    The YOUNGEST block's `M` is always symbolically `I` at the start of a layer,
    because it was born here and nothing has advanced it yet. It is therefore not
    stored, and `contract_W` materialises it as `W^T` at zero cost.

    `C_L` is not stored either. The two-leg block is born with
    `A_L = w1[:,None] * C11` and `C_L = (w2[:,None] * w1[None,:] * C11).T`, and
    `C11 = cov_pre * off_mask` is SYMMETRIC, so

        C_L[i,j] = w2[j] w1[i] C11[i,j] = A_L[i,j] w2[j]     i.e.  C_L = A_L diag(w2)

    That relation survives the lineage's whole life, because everything applied
    to it afterwards is a LEFT multiplication -- `contract_W` is `W^T X`,
    `contract_wick_` is `diag(col) X` -- and a left multiplication commutes with
    a right diagonal. So `C_L` is regenerated as `A_L * w2b` at `O(n^2)` instead
    of costing one `(n,n)@(n,n)` matmul per lineage per layer: **one matmul of
    the nine, 0.117 B at 1024x16.** Verified at n=256 float32: `cov_pre`'s own
    float32 asymmetry is `2.5e-07` relative and `fac3` vs `fac1 * w2` agrees to
    `7.8e-07`. Exact in real arithmetic, float32-round-off-limited here.
    """

    __slots__ = ("A_D", "A_L", "M", "w2b", "k",
                 # P2: the FACTORED leg. When `_P2_SEPARABLE`, `A_D` is None
                 # and these carry it exactly: `A_D = M d(sb) + 3 A_L d(eb)
                 # + Z L^T`. `Z` is `(n, k r)` and transported; `L` is
                 # `(k, n, r)` and STATIC; `sb`/`eb` are `(k n,)` column
                 # scales. `_p2` caches the per-layer reconstruction.
                 "Z", "L", "sb", "eb", "_p2",
                 # STAGE 1: the distinct-index kappa4 hubs. `Y` is `(n, 2k)`
                 # and TRANSPORTED (interleaved A/B per lineage); `CA`/`CB` are
                 # `(k n,)` STATIC column scales. `_hub` caches `_hub_parts`.
                 "Y", "CA", "CB", "_hub",
                 # STEP 3: shared coordinates of the OLD lineages
                 "Q", "FA", "FM", "ko", "Sg", "_legs", "_wts",
                 # STAGE 3: the consumed-query basis's two stashes
                 "_qU", "_qold", "F", "R3", "R4", "w3b", "_p3")

    def __init__(self, A_D, A_L, M, w2b, k,
                 Z=None, L=None, sb=None, eb=None):
        self.A_D, self.A_L, self.M, self.w2b, self.k = A_D, A_L, M, w2b, k
        self.Z, self.L, self.sb, self.eb = Z, L, sb, eb
        self._p2 = None
        self.Y = self.CA = self.CB = None
        self._hub = None
        self.Q = self.FA = self.FM = self.Sg = None
        self.ko = 0
        self._legs = self._wts = None
        self._qU = self._qold = None
        self.F = self.R3 = self.R4 = self.w3b = None
        self._p3 = None


# --------------------------------------------------------------------------
# BATCHED STRASSEN-WINOGRAD  (WP21, contract in experiments/LOG.md 2026-09-07)
# --------------------------------------------------------------------------
# Strassen replaces 8 sub-multiplications with 7 at every level, so counted
# FLOPs fall by roughly (7/8)^L. On flopscope the interesting fact is that the
# seven sub-products of a level can be issued as ONE BATCHED matmul -- a 3-D
# `fnp.matmul` is a single metered operation, billed at exactly
# `b * m * n * (2k - 1)` with no batching surcharge (measured to the FLOP at
# b = 128, `local_sim/p2_batched_matmul_probe.py`). So a whole level costs a
# FLAT 23 operations however wide the batch has grown, and the operation count
# grows LINEARLY in depth instead of as 7^L. The naive recursion issues ~1.1M
# operations per MLP and would blow the 0.4 s residual cliff 30x over.
#
# Slicing is free here (0 FLOPs, 0 operations -- it is a view), so the only
# billed glue is the ten Winograd additions, the two stacking concatenates and
# the eight reconstruction additions.
#
# MEASURED at 1024x16, per-call spelling, on the real shape census:
#
#     L    counted FLOPs        B        operations   predicted residual
#     0  1,714,554,351,206   0.77969        3,232        0.043 s
#     1  1,506,154,327,654   0.68492        6,268        0.084 s
#     2  1,328,654,462,566   0.60420        9,304        0.125 s
#     3  1,181,829,852,774   0.53743       12,340        0.165 s
#     4  1,068,211,920,486   0.48577       15,376        0.206 s
#
# against a 22,000-operation gate and a 0.4 s cliff.
#
# EXACT IN REAL ARITHMETIC, NOT IN FLOAT32. Strassen reassociates, and at these
# shapes the per-matmul error is 1.4-2.4x the plain float32 baseline at L=1 and
# 5.4-30x at L=4. Whether that costs SCORE is decided end-to-end on the 24 P01
# nets against the frozen gate in the contract, never by a per-matmul figure.

#: Recursion depth. 0 reproduces `estimator_k3_full.py` bit-for-bit.
_STRASSEN_DEPTH = 5


def _sb(A, B, depth):
    """Batched Strassen-Winograd. `A` is `(b,m,k)`, `B` is `(b,k,n)`.

    Every level multiplies the batch axis by 7 and halves each dimension, so
    the level is issued as ONE batched matmul however wide the batch already
    is. Falls back to a plain product the moment any dimension is odd, which is
    what keeps the file shape-generic (hard rule 7).
    """
    b = A.shape[0]
    m = A.shape[1]
    k = A.shape[2]
    n = B.shape[2]
    if depth <= 0 or (m % 2) or (k % 2) or (n % 2):
        return A @ B
    mh = m // 2
    kh = k // 2
    nh = n // 2

    a11 = A[:, :mh, :kh]
    a12 = A[:, :mh, kh:]
    a21 = A[:, mh:, :kh]
    a22 = A[:, mh:, kh:]
    b11 = B[:, :kh, :nh]
    b12 = B[:, :kh, nh:]
    b21 = B[:, kh:, :nh]
    b22 = B[:, kh:, nh:]

    SA = fnp.concatenate([a11 + a22, a21 + a22, a11, a22,
                          a11 + a12, a21 - a11, a12 - a22], axis=0)
    SB = fnp.concatenate([b11 + b22, b11, b12 - b22, b21 - b11,
                          b22, b11 + b12, b21 + b22], axis=0)

    P = _sb(SA, SB, depth - 1)
    p1 = P[0:b]
    p2 = P[b:2 * b]
    p3 = P[2 * b:3 * b]
    p4 = P[3 * b:4 * b]
    p5 = P[4 * b:5 * b]
    p6 = P[5 * b:6 * b]
    p7 = P[6 * b:7 * b]

    c11 = p1 + p4 - p5 + p7
    c12 = p3 + p5
    c21 = p2 + p4
    c22 = p1 - p2 + p3 + p6
    return fnp.concatenate([fnp.concatenate([c11, c12], axis=2),
                            fnp.concatenate([c21, c22], axis=2)], axis=1)


#: The smallest block a Strassen level may produce. Below this the Winograd glue
#: -- O(n^2) per level and growing as (7/4)^L -- outruns the O(n^3) saving, and
#: the recursion COSTS FLOPs instead of saving them. Measured 2026-09-08, counted
#: FLOPs for the whole chain at non-live shapes:
#:
#:     shape      L=0          L=2          L=4
#:     48 x 5     14,382,001   14,255,857   21,013,741   <- L=4 is 46% WORSE
#:     64 x 4     19,716,466   18,679,410   25,381,826
#:     96 x 3     31,960,667   28,743,707   35,085,287
#:
#: At the live shape the smallest operand dimension is 1024, so `1024 >> 4 = 64`
#: and the cap is not binding: L=4 is granted in full and the measured chain cost
#: is 0.48577 B. At 96 or below the cap refuses every level, which is the safe
#: direction. Hard rule 7 -- `estimator.py` stays shape-generic -- and this is
#: exactly the defect `_regen` was flagged for on 2026-09-07: a fixed depth that
#: is right at 1024 and over budget everywhere else.
_STRASSEN_MIN_BLOCK = 32


def _depth_for(m, k, n):
    """How many Strassen levels this shape can actually afford.

    Deterministic, shape-derived, and never larger than `_STRASSEN_DEPTH`.
    """
    lo = m if m < k else k
    lo = lo if lo < n else n
    d = 0
    while d < _STRASSEN_DEPTH and (lo >> (d + 1)) >= _STRASSEN_MIN_BLOCK:
        d += 1
    return d


def _mm(A, B):
    """The chain's ONE matmul spelling. `_STRASSEN_DEPTH = 0` is a plain `@`."""
    if _STRASSEN_DEPTH <= 0:
        return A @ B
    d = _depth_for(A.shape[0], A.shape[1], B.shape[1])
    if d <= 0:
        return A @ B
    return _sb(A[None], B[None], d)[0]


def _advance(WT, tw):
    """`contract_W` on the whole tower: THREE matmuls, whatever `k` is.

    The youngest block's `M` is symbolically `I`, and `W^T I` is `W^T` exactly,
    at zero FLOPs -- so it is concatenated in rather than multiplied.
    """
    A_D = None if tw.A_D is None else _mm(WT, tw.A_D)
    A_L = _mm(WT, tw.A_L)
    M = WT if tw.M is None else fnp.concatenate([_mm(WT, tw.M), WT], axis=1)
    # P2: `Z` is `(n, k r)`, so this is thin -- and it is the ONLY thing the
    # residual needs, because `L`, `sb` and `eb` are static under transport.
    # `A_D = M d(sb) + 3 A_L d(eb) + Z L^T` maps to
    # `W^T A_D = (W^T M) d(sb) + 3 (W^T A_L) d(eb) + (W^T Z) L^T`, which is the
    # same identity in the transported legs. That is why the leg survives.
    Z = None if tw.Z is None else _mm(WT, tw.Z)
    out = _Tower(A_D, A_L, M, tw.w2b, tw.k, Z, tw.L, tw.sb, tw.eb)
    if tw.Y is not None:
        # a hub's `y` is a LEFT factor: transported like a leg, one thin product
        out.Y, out.CA, out.CB = _mm(WT, tw.Y), tw.CA, tw.CB
    if tw.F is not None:
        out.F, out.R3, out.R4, out.w3b = _mm(WT, tw.F), tw.R3, tw.R4, tw.w3b
    return _carry_shared(out, tw, None if tw.Q is None else _mm(WT, tw.Q))


def _wick_tower(col, tw):
    """`contract_wick_` on the whole tower: THREE column scales.

    `col` is `(n, 1)` and broadcasts across every block at once. `w2b` is a RIGHT
    diagonal, so a left scale does not touch it, and the `3` on the two-leg
    block's middle mode stays a Python scalar and is never materialised.
    """
    # A left column scale distributes over the factored leg exactly as it does
    # over the dense one: `(A_D)*col = (M*col) d(sb) + 3 (A_L*col) d(eb)
    # + (Z*col) L^T`. `sb`/`eb` are RIGHT diagonals and are untouched.
    out = _Tower(None if tw.A_D is None else tw.A_D * col,
                 tw.A_L * col, tw.M * col, tw.w2b, tw.k,
                 None if tw.Z is None else tw.Z * col,
                 tw.L, tw.sb, tw.eb)
    if tw.Y is not None:
        # left scale on every mode of Sym3(y (x) S): y, and both legs of S
        out.Y, out.CA, out.CB = tw.Y * col, tw.CA, tw.CB
    _carry_shared(out, tw, None if tw.Q is None else tw.Q * col)
    out._wts = tw._wts
    if tw.F is not None:
        out.F, out.R3, out.R4, out.w3b = tw.F * col, tw.R3, tw.R4, tw.w3b
    return out


def _p2_compress(R):
    """`3 R^T ~= Z L^T` by a range finder with one power iteration.

    THE SKETCH IS THE RESIDUAL'S OWN STRONGEST COLUMNS, selected by norm. That
    is deterministic -- nothing is sampled, so hard rule 2 is satisfied by
    construction -- and, unlike a fixed slice of the weight matrix, it is
    **permutation-equivariant**.

    Why that matters, measured rather than assumed. The first version of this
    function used `W[:, :r]`, the layer's own leading weight columns (which is
    what 504aldo ship). Relabelling the hidden neurons permutes those columns,
    so "the first r" selects a DIFFERENT subspace, the range finder keeps
    different directions, and the truncation error lands somewhere else. The
    invariant suite caught it: `inv_permutation` went from v30's 1e-13 to
    1.07% of raw MSE at 128x8 and FAILED its 1% bar. A standalone check put the
    two side by side -- column-slice sketch `8.8e-01` relative, this sketch
    `3.2e-07`, which is float32 precision.

    Selecting by norm is equivariant because the norms permute with the
    columns, so the selected SET is the same set, and only the projector
    `Q Q^T` -- not the basis inside it -- reaches the output.

    `_P2_RANK <= 0` sketches with `R` itself, which makes the range finder
    exact and the reconstruction a float32 copy of the dense `A_D`.

    Returns `(Z, L)` with the factor 3 already folded into `Z`, so the
    consumers never carry it.
    """
    n = R.shape[0]
    r = n if _P2_RANK <= 0 else min(int(_P2_RANK), n)
    Om = R if r >= n else R[:, fnp.argsort((R * R).sum(axis=0))[-r:]]
    Q, _ = fnp.linalg.qr(_mm(R, Om))
    Q, _ = fnp.linalg.qr(_mm(R, _mm(R.T, Q)))
    return _mm(Q.T, R).T * 3.0, Q


def _p2_recon(tw):
    """The shared per-layer reconstruction: `(A_D.M, M.M, (M.M)L, r)`.

    `A_D` is NOT materialised. What both slices actually read is `A_D . M`, so
    only that product is formed:

        A_D . M = M.M.s + 3 A_L.M.e + Zres.M ,   Zres = Z L^T

    `Zres` is the one dense `(n, k n)` array P2 adds, at `O(k n^2 r)` -- and P2
    removes three of F21's: the `_advance` output for `A_D`, `A_D . M`, and the
    `M.M @ A_D^T` product. Cached on the tower because `_dslice3` and
    `_dslice21` are both called on the same object in one layer.

    The `(n, k n) <-> (k, n, n)` shuttles are the price of F21's WIDE layout
    against the per-lineage blocking the thin terms need. They are memory
    traffic, not FLOPs, and they are what the residual measurement has to
    clear.
    """
    A_L, M = _full_legs_lean(tw)
    if tw._p2 is not None:
        return tw._p2
    n, k = M.shape[0], tw.k
    r = tw.L.shape[2]
    # (n, k r) -> (k, n, r): SMALL, `k n r` not `k n^2`.
    Z3 = fnp.reshape(tw.Z, (n, k, r)).transpose(1, 0, 2)
    Zres = fnp.reshape((Z3 @ tw.L.transpose(0, 2, 1)).transpose(1, 0, 2),
                       (n, k * n))
    PP = M * M
    MP = PP * tw.sb + (A_L * M) * (3.0 * tw.eb) + Zres * M
    PPL = fnp.reshape(PP, (n, k, n)).transpose(1, 0, 2) @ tw.L
    tw._p2 = (MP, PP, fnp.reshape(PPL.transpose(1, 0, 2), (n, k * r)))
    return tw._p2


def _hub_parts(tw):
    """The distinct-index kappa4 hubs' shared per-layer pieces: `(G, RY)`.

    `G = sum_h y_h . c_h` in the wide `(n, k n)` layout (y broadcast over its
    lineage's columns) and `RY` the `(n, 2k)` stack of `R_h = (A_L . M) c_h`,
    interleaved `[A_1, B_1, A_2, B_2, ...]` like `Y`. Cached on the tower
    because `_dslice3` and `_dslice21` read the same object in one layer.
    All `O(k n^2)` elementwise work; no matmul.
    """
    A_L, M = _full_legs_lean(tw)
    if tw._hub is not None:
        return tw._hub
    n, k = M.shape[0], tw.k
    Y3 = fnp.reshape(tw.Y, (n, k, 2))
    cA = fnp.reshape(tw.CA, (k, n))
    cB = fnp.reshape(tw.CB, (k, n))
    yA = Y3[:, :, 0]
    yB = Y3[:, :, 1]
    G = fnp.reshape(yA[:, :, None] * cA[None, :, :] + yB[:, :, None] * cB[None, :, :],
                    (n, k * n))
    AM3 = fnp.reshape(A_L * M, (n, k, n))
    RA = (AM3 * cA[None, :, :]).sum(axis=2)
    RB = (AM3 * cB[None, :, :]).sum(axis=2)
    RY = fnp.reshape(fnp.stack([RA, RB], axis=2), (n, 2 * k))
    tw._hub = (G, RY)
    return tw._hub


def _p4_sym_sandwich(WT, cov, W):
    """`W^T C W` for symmetric `C`, paying 3/4 of the second product.

    Rows `[:h]` give blocks 11 and 12 in one product; block 22 is its own
    quarter product; block 21 is block 12 transposed -- exact in real
    arithmetic because the result is symmetric. Odd width: plain product.
    """
    X = _mm(WT, cov)
    n = X.shape[0]
    if n % 2:
        return _mm(X, W)
    h = n // 2
    top = _mm(X[:h], W)
    b22 = _mm(X[h:], W[:, h:])
    return fnp.concatenate([top, fnp.concatenate([top[:, h:].T, b22], axis=1)], axis=0)


def _p3_compress(D):
    """`D ~= U V^T` at rank `_P3_RANK` (0 = full) by the equivariant range finder
    `_p2_compress` uses: the sketch is `D`'s own strongest columns by norm."""
    n = D.shape[0]
    r = n if _P3_RANK <= 0 else min(int(_P3_RANK), n)
    Om = D if r >= n else D[:, fnp.argsort((D * D).sum(axis=0))[-r:]]
    Q, _ = fnp.linalg.qr(_mm(D, Om))
    Q, _ = fnp.linalg.qr(_mm(D, _mm(D.T, Q)))
    return Q, _mm(Q.T, D).T


def _p3_parts(tw):
    """P3's shared per-layer pieces `(Gp, TT, d3p)`, cached on the tower.

    `Gp = A1 . w3b + A2 . w2b` in the wide `(n, k n)` layout, `TT` the thin
    left factors `(M.A_L.c) R` interleaved like `F`, `d3p` the D3 addition.
    """
    if tw._p3 is not None:
        return tw._p3
    n, k = tw.M.shape[0], tw.k
    r = tw.R3.shape[2]
    F4 = fnp.reshape(tw.F, (n, k, 2 * r)).transpose(1, 0, 2)
    A1 = fnp.reshape((F4[:, :, :r] @ tw.R3.transpose(0, 2, 1)).transpose(1, 0, 2), (n, k * n))
    A2 = fnp.reshape((F4[:, :, r:] @ tw.R4.transpose(0, 2, 1)).transpose(1, 0, 2), (n, k * n))
    Gp = A1 * tw.w3b + A2 * tw.w2b
    A_L, M = _full_legs_lean(tw)
    AM = A_L * M
    MC3 = fnp.reshape(AM * tw.w3b, (n, k, n)).transpose(1, 0, 2) @ tw.R3
    MC2 = fnp.reshape(AM * tw.w2b, (n, k, n)).transpose(1, 0, 2) @ tw.R4
    TT = fnp.reshape(fnp.concatenate([MC3, MC2], axis=2).transpose(1, 0, 2), (n, 2 * k * r))
    d3p = (Gp * AM).sum(axis=1) * 3.0
    tw._p3 = (Gp, TT, d3p)
    return tw._p3


def _dslice3(tw):
    """The `(3,)` repeated slice of the whole tower. All O(n^2 k), no matmul.

    D block  -> sum_j A_D M M ; L block -> 3 sum_j A_L M C_L. Summing over ALL
    `k n` columns performs the sum over lineages, exactly as the contraction in
    `_dslice21` does.
    """
    A_L, M = _full_legs_lean(tw)
    C_L = A_L * tw.w2b
    if tw.A_D is None:
        # `A_D . M` is already formed and shared; the second term is F21's own,
        # unchanged, because `C_L = A_L d(w2)` never involved `A_D`.
        MP, _PP, _PPL = _p2_recon(tw)
        d3 = (MP * M).sum(axis=1) + 3.0 * (A_L * M * C_L).sum(axis=1)
        if tw.Y is not None:
            # D3 += 2 sum_h y_h . R_h
            _G, RY = _hub_parts(tw)
            d3 = d3 + (RY * tw.Y).sum(axis=1) * 2.0
        if tw.F is not None:
            d3 = d3 + _p3_parts(tw)[2]
        return d3
    t = (tw.A_D * M * M).sum(axis=1)
    return t + 3.0 * (A_L * M * C_L).sum(axis=1)


def _dslice21(tw, off_mask):
    """The `(2,1)` repeated slice of the whole tower: three matmuls, whatever `k`.

    D block, factors `(A_D, M, M)`:
        {0,1}|{2} -> (A_D . M) @ M^T
        {0,2}|{1} -> (A_D . M) @ M^T      <-- identically the same product
        {1,2}|{0} -> (M . M) @ A_D^T
    L block, factors `(A_L, 3M, C_L)`, and because `C_L = A_L diag(w2)` the SAME
    collapse happens here:
        {0,1}|{2} -> (A_L . M) @ C_L^T
        {1,2}|{0} -> (A_L . M) @ C_L^T    <-- identically the same product
        {0,2}|{1} -> (A_L . C_L) @ M^T
    The two products with right operand M.T share one fused left operand.
    Thus three distinct matmuls remain; the 3 stays a Python scalar.

    Each is one `(n, k n) @ (k n, n)`, and the contraction over the `k n` columns
    IS the sum over lineages. The `2! 1! / 3! = 1/3` coefficient and the diagonal
    kill are applied ONCE at the end -- both are linear.
    """
    A_L, M = _full_legs_lean(tw)
    C_L = A_L * tw.w2b
    if tw.A_D is None:
        # THE REGROUPING, proved in `local_sim/p2_p2_identity_test.py` to
        # 6.8e-16 with an arbitrary residual. Substituting
        # `A_D = M d(sb) + 3 A_L d(eb) + Z L^T` on the RIGHT of F21's three
        # contractions sends two of its pieces into groups that already exist,
        # leaving right factors `A_L`, `M` and a THIN `Z`. The `1/3` and the
        # diagonal kill are still applied once, at the end.
        MP, PP, PPL = _p2_recon(tw)
        LA = 2.0 * (A_L * M) * tw.w2b + PP * tw.eb
        LP = (A_L * A_L) * tw.w2b + PP * (tw.sb / 3.0) + (2.0 / 3.0) * MP
        if tw.Y is not None:
            # the hubs FOLD INTO the two existing contractions -- no new dense
            # product: (2/3)(y.A_L.c) M^T joins LP, (2/3)(y.M.c) A_L^T joins LA
            G, RY = _hub_parts(tw)
            G23 = G * (2.0 / 3.0)
            LA = LA + G23 * M
            LP = LP + G23 * A_L
        if tw.F is not None:
            Gp, TT, _ = _p3_parts(tw)
            LA = LA + Gp * M
            LP = LP + Gp * A_L
        acc = _shared_contract_lean(tw, LA, LP, A_L, M)
        if tw.F is not None:
            acc = acc + _mm(TT, tw.F.T)
        if tw.Y is not None:
            acc = acc + _mm(RY * (2.0 / 3.0), tw.Y.T)
        # the thin leg: one `(n, k r) @ (k r, n)`, and the contraction over the
        # `k r` columns IS the sum over lineages -- the same trick the wide
        # layout already uses for the `k n` columns.
        return (acc + _mm(PPL, tw.Z.T) * (1.0 / 3.0)) * off_mask
    acc = _mm(2.0 * (tw.A_D * M) + 3.0 * (A_L * C_L), M.T)
    acc = acc + _mm(M * M, tw.A_D.T)
    # {0,1}|{2} and {1,2}|{0} are IDENTICALLY THE SAME PRODUCT, for the same
    # reason the D block's two are: `C_L = A_L diag(w2)`, so
    #   {0,1}|{2}[a,i] = sum_j A_L[a,j] M[a,j] A_L[i,j] w2[j]
    #   {1,2}|{0}[a,i] = sum_j M[a,j] A_L[a,j] w2[j] A_L[i,j]
    # and the two summands are the same floats in a different written order.
    # Verified numerically at n=64, k=3: `1.7e-16` relative, against `1.5e+00`
    # and `1.3e+00` for the genuinely distinct pairs. So the two-leg block needs
    # TWO matmuls, not three -- one of eight per lineage per layer.
    acc = acc + 6.0 * _mm(A_L * M, C_L.T)
    return (acc / 3.0) * off_mask


def _append(tw, A_D, A_L, w2b, n, Zb=None, Lb=None, sb=None, eb=None,
            Y=None, CA=None, CB=None):
    """Add the block born at this layer. Its `M` is `I` and is not stored.

    P2 appends the FACTORED leg instead of a dense `A_D`: `Z` grows by `r`
    columns, `L` by one `(n, r)` page, and `sb`/`eb` by `n` entries each.
    """
    if tw is None:
        out = _Tower(A_D, A_L, None, w2b, 1, Zb,
                     None if Lb is None else Lb[None], sb, eb)
        if Y is not None:
            out.Y, out.CA, out.CB = Y, CA, CB
        return out
    out = _Tower(None if A_D is None else fnp.concatenate([tw.A_D, A_D], axis=1),
                 fnp.concatenate([tw.A_L, A_L], axis=1),
                 tw.M, fnp.concatenate([tw.w2b, w2b]), tw.k + 1,
                 None if Zb is None else fnp.concatenate([tw.Z, Zb], axis=1),
                 None if Lb is None else fnp.concatenate([tw.L, Lb[None]], axis=0),
                 None if sb is None else fnp.concatenate([tw.sb, sb]),
                 None if eb is None else fnp.concatenate([tw.eb, eb]))
    if Y is not None:
        out.Y = fnp.concatenate([tw.Y, Y], axis=1)
        out.CA = fnp.concatenate([tw.CA, CA])
        out.CB = fnp.concatenate([tw.CB, CB])
    if tw is not None and tw.F is not None:
        out.F, out.R3, out.R4, out.w3b = tw.F, tw.R3, tw.R4, tw.w3b
    return _carry_shared(out, tw, tw.Q)


def _truncate(tw, gens, n):
    """Drop the OLDEST lineages, keeping the `gens` youngest.

    MEASURED TO BE A LOSING TRADE at 1024x16 (2026-09-05, 24 nets: raw MSE
    4.00e-08 exact vs 4.36e-08 at 12 generations and 5.06e-08 at 11, against a
    budget saving that is only linear). It exists solely as the budget guard of
    last resort, and `_fit_generations` chooses `None` -- the exact tower --
    wherever the shape allows it, which at the live shape it does.
    """
    if tw is None or gens is None or tw.k <= gens:
        return tw
    g = int(gens)
    keep = g * n
    # `M` holds the OLDER k-1 blocks, so it keeps one fewer block than the rest.
    M = None if (tw.M is None or g <= 1) else tw.M[:, -((g - 1) * n):]
    if tw.A_D is None:
        r = tw.L.shape[2]
        out = _Tower(None, tw.A_L[:, -keep:], M, tw.w2b[-keep:], g,
                     tw.Z[:, -(g * r):], tw.L[-g:],
                     tw.sb[-keep:], tw.eb[-keep:])
        if tw.Y is not None:
            out.Y, out.CA, out.CB = tw.Y[:, -(2 * g):], tw.CA[-keep:], tw.CB[-keep:]
        if tw.F is not None:
            r3 = tw.R3.shape[2]
            out.F, out.R3, out.R4 = tw.F[:, -(2 * g * r3):], tw.R3[-g:], tw.R4[-g:]
            out.w3b = tw.w3b[-keep:]
        return out
    return _Tower(tw.A_D[:, -keep:], tw.A_L[:, -keep:], M, tw.w2b[-keep:], g)


# ==========================================================================
# the cost model: priced from the shapes, in pure Python, before anything runs
# ==========================================================================
# flopscope bills `(m,k) @ (k,n)` at `m n (2k - 1)`. Every dominant operation in
# the tower is `(n,n) @ (n,n)`, so the whole bill is a matmul COUNT times one
# constant. Verified against the meter at `1024 x 16`: the model says
# 1,022 matmuls = 2,193,656,573,504 FLOPs and the meter reads
# 2,197,635,040,924, i.e. the model is 0.18% low and `_ELEM_PER_LAYER` covers
# the elementwise remainder with margin.
#
# Nothing here touches a flopscope array, so the audit itself costs zero FLOPs
# and zero operations -- which is the point. An audit that had to be metered
# could not be run before deciding whether to spend the budget.

#: Elementwise FLOPs per layer per element, with margin. Measured 237.
_ELEM_PER_LAYER = 400

#: Below this fraction of B the tower is spent as designed. Above it, generations
#: are dropped until it fits. 0.95 leaves 5% of B for the elementwise model being
#: wrong, for the server's per-MLP offset (measured at most 2**24 = 0.0008% of B)
#: and for whatever a shape we have never run costs.
_BUDGET_FRACTION = 0.95


def _matmuls(depth, gens):
    """How many (n,n)@(n,n) matmuls the tower issues at `gens` carried lineages.

    `gens = None` is the exact tower. Layer `l` enters with `min(l, gens)`
    lineages; one of them is the youngest and is a matmul cheaper.
    """
    total = 0
    for l in range(depth):
        k = l if gens is None else min(l, gens)
        young = 1 if k >= 1 else 0
        aged = k - young
        if l == depth - 1:
            # last layer: transports only, no birth and no slices.
            total += 2 + (aged * 2 + young * 1 if _P2_SEPARABLE
                          else aged * 3 + young * 2)
        else:
            # P2's `4`/`3` is READ OFF THE CODE: 2 transports (A_L, M; the
            # youngest M is `I` and free) + 2 contractions (LA A_L^T, LP M^T).
            # F21's `7`/`6` is left exactly as it stands even though the code
            # issues 6/5 -- see this generator's header. It only picks `gens`.
            total += 2 + (aged * 4 + young * 3 if _P2_SEPARABLE
                          else aged * 7 + young * 6)
    return total


def _projected_flops(n, depth, gens):
    """The counted FLOPs the tower will bill, from the shapes alone."""
    base = (_matmuls(depth, gens) * n * n * (2 * n - 1)
            + _ELEM_PER_LAYER * n * n * depth)
    if not _P2_SEPARABLE:
        return base
    # THIS IS THE BUDGET GUARD, not a report: `predict` consults it before
    # issuing an operation, and an MLP over `B` scores as zeros. It must
    # OVER-predict. The first version charged `4 k n^2 r` and did neither:
    #   * it used `k n^2 r` per product where flopscope's convention -- which
    #     this function's OWN base term above uses -- is `n n (2n-1)`, so it
    #     was under by exactly 2x; and
    #   * it omitted `_p2_compress` completely.
    # Measured consequence before the fix: the guard came in at 0.898 of the
    # true cost at 96x6, consuming twice the margin `_BUDGET_FRACTION = 0.95`
    # is documented as holding. Found by an independent Skeptic, 2026-09-15.
    r = n if _P2_RANK <= 0 else min(int(_P2_RANK), n)
    thin = 0
    for l in range(depth):
        k = l if gens is None else min(l, gens)
        if k:
            thin += n * (k * r) * (2 * n - 1)      # W^T Z, the transport
            thin += k * n * n * (2 * r - 1)        # Z L^T, the reconstruction
            thin += k * n * r * (2 * n - 1)        # (M.M) L
            thin += n * n * (2 * k * r - 1)        # [(M.M) L] Z^T
        if l < depth - 1:                          # a birth, so a compression
            # four `(n,n)@(n,r)`-class products, TWO QRs, and the column norms.
            # The QR term is `2 n r^2` per factorisation with its `-(2/3) r^3`
            # dropped, because this is a guard: an over-charge costs a little
            # conservatism and an under-charge costs the whole MLP. At the
            # dense arm's `r = n` the QRs are cubic and omitting them left the
            # guard at 0.9955 -- under, and therefore useless.
            thin += 4 * n * r * (2 * n - 1) + 4 * n * r * r + 2 * n * n
        if _HUB_ROUTES and k:
            # STAGE 1 hubs, over-charged on purpose (this is the budget guard):
            # Y transport, the (n,2k)@(2k,n) contraction, and ~16 k n^2 of
            # elementwise G / R / LA / LP / D3 work.
            thin += n * (2 * k) * (2 * n - 1) + n * n * (4 * k - 1) + 16 * k * n * n
        if _HUB_ROUTES and l < depth - 1:
            thin += 12 * n * n                     # birth-time hub construction
        if _CLOSURE_SCOPE == "all" and l < depth - 1:
            thin += (_CLOSURE_NBIV * 40 + 200) * n * n   # extra-term stacks + 3 einsums
        if _PROTECT_FEED:
            q = _PROTECT_Q
            thin += k * n * n * (2 * q) + n * (k * q) * (2 * n - 1) + k * n * q * (2 * n - 1)
            thin += n * n * (2 * k * q) + (4 * q + 8) * n * n
        if _P3_ON:
            r3 = n if _P3_RANK <= 0 else min(int(_P3_RANK), n)
            if k:
                thin += n * (2 * k * r3) * (2 * n - 1)
                thin += 2 * k * n * n * (2 * r3 - 1)
                thin += 2 * k * n * r3 * (2 * n - 1)
                thin += n * n * (4 * k * r3 - 1) + 20 * k * n * n
            if l < depth - 1:
                thin += 4 * n * r3 * (2 * n - 1) + 4 * n * r3 * r3
                thin += n * n * (2 * r3 - 1) + 14 * n * n
    return base + thin


def _fit_generations(n, depth, budget):
    """The largest generation cap whose projected cost clears the budget bar.

    Returns `None` for the exact tower, an int for a trimmed one, or `-1` when
    even a single carried generation does not fit -- the caller then drops to the
    regenerating tower, which is `0.077 B` at `1024 x 16`.
    """
    bar = _BUDGET_FRACTION * float(budget)
    if _projected_flops(n, depth, None) <= bar:
        return None
    for g in range(depth - 1, 0, -1):
        if _projected_flops(n, depth, g) <= bar:
            return g
    return -1


