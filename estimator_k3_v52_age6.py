    ok = len(ones_d) == 3 * len(ps) and all(
        sorted((tuple(tuple(b["vec"]) for b in r["blocks"]),
                round(float(r["scalar"]), 12))
               for r in ones_d if r["int_part"][0] == p) == want for p in ps)
