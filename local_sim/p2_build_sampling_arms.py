"""Generate the P2-CP1 SAMPLING arms -- self-contained and grader-legal.

Companion to `p2_build_arms.py`, which generates the analytic ladder. These share
no math with it, so they live in their own generator rather than growing a mode
flag on that one.

## The cost facts these arms are designed around, all MEASURED under flopscope

At 1024 x 16 with `B = 2^41` (`local_sim/p2_price_delta.py`, and the probe in
`experiments/LOG.md` 2026-08-21):

    one sample, all 16 layers, float32       33,587,196 FLOPs
    the pure forward identity 2 d w^2        33,554,432        (+0.10% overhead)
    max N at C/B = 1.0                       65,472
    max N at C/B = 0.1  (the multiplier floor)  6,547
    qr(1024 x 1024) float32                  2,863,311,532     = 0.0013 B
    stats.norm.ppf, per element              ~170 FLOPs, and it PROMOTES f32->f64

**The overhead is 0.10%, not the 0.4-1% the dataset card quotes for the reference
bake.** So the card's "65,536 effective samples" is very nearly achievable -- but
only *very nearly*, and the difference matters: exceeding `B` raises
`BudgetExhaustedError`, which the grader scores as a **failure** -- multiplier 1.0
against **zeroed** predictions, roughly 5x worse than merely spending the budget.
Every arm here therefore sizes `N` from the *measured* per-sample cost with a
safety margin, and sizes it from `budget`, never from a constant.

## Why both a full-budget and a floor-budget sampling arm

Above the floor a pure `1/N` estimator's score is **flat**: `MSE x max(0.1, C/B)`
= `(V/N) x (N c / B)` = `V c / B`, independent of N. So `sample_iid_max` and
`sample_iid_floor` should score the SAME, and the pair is a direct test of that
identity on real data rather than an assumption carried from Phase 1. If they
differ, the flat law is broken at this operating point and every argument built on
it has to be re-examined -- which is exactly what happened once already
(`docs/GOTCHAS.md`, T2, 2026-08-19).

## Arms

    sample_iid_max     i.i.d. Gaussian at the largest N that fits ~0.95 B
    sample_iid_floor   i.i.d. Gaussian at the largest N that fits the 0.1 floor
    sample_orth        orthogonal Monte Carlo (Choromanski et al. 2019): random
                       orthogonal bases with chi-distributed radii, matched to
                       `sample_iid_floor` on ROWS so the comparison is variance
                       reduction and not a budget difference
    sample_lattice     randomised rank-1 lattice (Korobov) + inverse-CDF, the
                       QMC comparator. No direction-number table is needed, which
                       is why it is here and a 1024-dimensional Sobol arm is not

Every arm keeps the **exact layer-1 row**, so they differ from the analytic ladder
only in how layers 2..16 are estimated.

Run:  uv run python local_sim/p2_build_sampling_arms.py
      uv run python local_sim/p2_build_sampling_arms.py --check
"""

from __future__ import annotations

import argparse
import hashlib
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
ARMS = os.path.join(_HERE, "p2_arms")

PREAMBLE = '''"""P2-CP1 sampling arm: {name}.

{blurb}

GENERATED by local_sim/p2_build_sampling_arms.py -- do not edit. Edit the
generator, which holds the shared budget arithmetic once.

Grader-legal: flopscope, flopscope.numpy, whestbench, stdlib only. Never mutates
a grader array. Shape-generic. Randomness derives from `mlp.seed` alone.
"""

import flopscope as flops
import flopscope.numpy as fnp
from whestbench import MLP, BaseEstimator

_INV_SQRT_2PI = 0.3989422804014327

#: MEASURED at 1024 x 16 under flopscope 0.10 and 0.12 (identical): one sample
#: through all layers costs 33,587,196 FLOPs against the 2*d*w^2 = 33,554,432
#: identity, i.e. 0.10% overhead. Expressed as a ratio so it stays shape-generic.
_OVERHEAD = 1.0011

#: Fraction of the budget the arm aims to spend. NOT a tuned constant: exceeding
#: B raises BudgetExhaustedError, which the grader scores as a FAILURE -- zeroed
#: predictions AND multiplier 1.0, about 5x worse than simply spending B. The
#: margin buys nothing except never touching that cliff.
_TARGET_CB = {target_cb}

#: Rows per chunk. flopscope bills the release of large temporaries as residual
#: wall time at ~100-120 us/op against ~6-8 us when release is deferred
#: (docs/GOTCHAS.md, forum 18101), so the rule is FEWER, LARGER ops. 4096 rows
#: at width 1024 in float32 is 16.8 MB per activation -- comfortably inside the
#: 64 GB package-default RLIMIT_AS while keeping the op count at N/4096.
_CHUNK = 4096


class Estimator(BaseEstimator):
    """{name}."""

    def setup(self, context) -> None:
        return None

    def _n_samples(self, width, depth, budget):
        """Largest N that fits `_TARGET_CB * budget`, sized from MEASURED cost."""
        per = 2.0 * depth * width * width * _OVERHEAD
        n = int(_TARGET_CB * float(budget) / per)
        return max(n, 1)

    def _exact_first_layer(self, w0):
        var = (w0 * w0).sum(axis=0, dtype=fnp.float64)
        return fnp.sqrt(var) * _INV_SQRT_2PI

    def _accumulate(self, w, x):
        """Forward one chunk, returning the per-layer column sums."""
        h = x
        out = []
        for wk in w:
            h = fnp.maximum(h @ wk, 0.0)
            out.append(fnp.sum(h, axis=0, dtype=fnp.float64))
        return out
'''

DRAW_IID = '''
    def _draw(self, rng, m, width, k):
        return rng.standard_normal((m, width), dtype=fnp.float32)
'''

DRAW_ORTH = '''
    def _draw(self, rng, m, width, k):
        """Orthogonal Monte Carlo: rows of a random orthogonal basis, rescaled.

        Choromanski et al. (2019). Take `Q` Haar-orthogonal, then `r_i * Q[i, :]`
        with `r_i` chi-distributed with `width` degrees of freedom has exactly the
        N(0, I) marginal, while the rows are exactly orthogonal instead of
        approximately so. The variance reduction comes from removing the
        realised correlation between directions, which iid sampling leaves in.

        A basis supplies `width` rows, so a chunk of `m` rows uses
        `ceil(m / width)` bases. `qr` on a 1024 x 1024 float32 costs 2.86e9 =
        0.0013 B, so 16 bases (16,384 rows) cost 2% of the budget on top of the
        propagation -- charged, not ignored.
        """
        cols = []
        rows_left = m
        while rows_left > 0:
            g = rng.standard_normal((width, width), dtype=fnp.float32)
            q, r = fnp.linalg.qr(g)
            # Sign-fix so the basis is Haar rather than QR-implementation
            # dependent: without it the sign convention of the LAPACK routine
            # leaks into the point set.
            q = q * fnp.sign(fnp.diagonal(r))
            chi = fnp.sqrt(fnp.sum(
                rng.standard_normal((width, width), dtype=fnp.float32) ** 2,
                axis=1))
            block = q * fnp.reshape(chi, (width, 1))
            take = min(rows_left, width)
            cols.append(block[:take])
            rows_left -= take
        return fnp.concatenate(cols, axis=0) if len(cols) > 1 else cols[0]
'''

DRAW_LATTICE = '''
    def _draw(self, rng, m, width, k):
        """Randomised rank-1 lattice (Korobov) mapped through the inverse CDF.

        Point i is `frac(i * g / N + shift)`, then `Phi^-1`. A rank-1 lattice
        needs only a generating vector, so unlike Sobol it carries no
        direction-number table -- which is the entire reason this is the QMC arm
        and a 1024-dimensional Sobol arm is not.

        The random shift makes it an unbiased estimator of the same integral,
        exactly as a digital shift does for Sobol.

        `stats.norm.ppf` PROMOTES float32 to float64 to match scipy
        (flopscope >= 0.10, forum 18127), so the result is cast back before it
        reaches the propagation -- otherwise every downstream matmul is billed at
        the float64 rate and the arm silently costs twice what it should.
        """
        idx = fnp.reshape(fnp.arange(k, k + m, dtype=fnp.float64), (m, 1))
        gen = fnp.reshape(self._gen, (1, width))
        u = idx * gen + fnp.reshape(self._shift, (1, width))
        u = u - fnp.floor(u)
        # Never exactly 0 or 1: ppf would return -inf / +inf.
        u = fnp.minimum(fnp.maximum(u, 1e-9), 1.0 - 1e-9)
        return flops.stats.norm.ppf(u).astype(fnp.float32)
'''

PREDICT = '''
    def predict(self, mlp: MLP, budget: int) -> fnp.ndarray:
        width = mlp.width
        depth = len(mlp.weights)
        w = [x.astype(fnp.float32) for x in mlp.weights]
        n = self._n_samples(width, depth, budget)
        rng = fnp.random.default_rng(int(mlp.seed))
{setup_extra}
        totals = None
        done = 0
        while done < n:
            m = min(_CHUNK, n - done)
            x = self._draw(rng, m, width, done)
            part = self._accumulate(w, x)
            totals = part if totals is None else [a + b for a, b in zip(totals, part)]
            done += m

        rows = [t / float(n) for t in totals]
        rows[0] = self._exact_first_layer(w[0].astype(fnp.float64))
        return fnp.stack(rows, axis=0)
'''

LATTICE_SETUP = '''        # Generating vector: a fixed Korobov form a^j mod n, with `a` derived
        # from n so it is a property of the point count and not a tuned constant.
        a = 1
        base = (n // 3) | 1
        gv = []
        for _j in range(width):
            gv.append(float(a) / float(n))
            a = (a * base) % n if n > 1 else 1
        self._gen = fnp.asarray(gv, dtype=fnp.float64)
        self._shift = rng.random(width, dtype=fnp.float64)
'''

SPECS = [
    ("sample_iid_max", DRAW_IID, 0.95, "",
     "i.i.d. Gaussian Monte Carlo at the largest N that fits ~0.95 B. This is the\n"
     "reference the dataset card's 'effective MC samples' column describes, run at\n"
     "the real measured per-sample cost rather than at the card's upper bound."),
    ("sample_iid_floor", DRAW_IID, 0.10, "",
     "i.i.d. Gaussian Monte Carlo at the largest N that fits the 0.1 multiplier\n"
     "floor. Paired with sample_iid_max this is a direct test of the flat-score\n"
     "law: above the floor a 1/N estimator's score does not depend on N, so these\n"
     "two must agree. If they do not, the law is broken here."),
    ("sample_orth", DRAW_ORTH, 0.10, "",
     "Orthogonal Monte Carlo at the floor budget, matched to sample_iid_floor on\n"
     "ROWS so the comparison isolates variance reduction from budget. The QR cost\n"
     "is charged, not ignored."),
    ("sample_lattice", DRAW_LATTICE, 0.10, LATTICE_SETUP,
     "Randomised rank-1 lattice (Korobov) + inverse CDF at the floor budget. The\n"
     "QMC comparator that needs no direction-number table."),
]


def build() -> dict:
    os.makedirs(ARMS, exist_ok=True)
    out = {}
    for name, draw, target, extra, blurb in SPECS:
        src = (PREAMBLE.format(name=name, blurb=blurb, target_cb=target)
               + draw + PREDICT.format(setup_extra=extra))
        out[name] = (os.path.join(ARMS, f"arm_{name}.py"), src)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    built = build()
    drift = []
    print("=" * 78)
    print("P2-CP1 SAMPLING ARMS")
    print("=" * 78)
    for name, (path, src) in built.items():
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if a.check:
            state = "DRIFT" if old != src else "ok"
            if old != src:
                drift.append(name)
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(src)
            state = "written" if old != src else "unchanged"
        print(f"  {name:<18} {state:<10} {len(src):>6} bytes  "
              f"sha256 {hashlib.sha256(src.encode()).hexdigest()[:16]}")
    print("=" * 78)
    if drift:
        print(f"  DRIFT in {drift}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
