"""Stage-1b candidate: complete first-order kappa4 (x C) content of the BIVARIATE moment slices.

Derivation (independent, label-free; checked against the exact scale-mixture law
in `experiments/2026-09-16_stage1b_rep/`). With z ~ N(mu, I + eps C) plus the
estimator's fourth-cumulant model kappa4 = m Sym(G (x) I), G = diag(dG) + lam C_off:

    kappa4_aaaa = m dG_a,  kappa4_aabb = (m/6)(dG_a + dG_b),  kappa4_aaab = (m/2) lam C_ab.

Expanding E[y_a^p y_b^q] to first order in kappa4 and in C, with
w(k,p) = E[(d/dz)^k y^p]:

    (1/24)[ k_aaaa w(4,p)w(0,q) + 4 k_aaab w(3,p)w(1,q) + 6 k_aabb w(2,p)w(2,q) + ... ]
  + C_ab * (the same kappa4 terms with one extra derivative on each side)

SIMPLE's table already carries the kappa4_aaaa and kappa4_aabb terms at C^0.
MISSING, and added to pK[(p,q)] for (p,q) in {(1,1),(2,1),(2,2)}:

    (q31)  (m lam / 12) C_ab [ w(3,p)_a w(1,q)_b + w(1,p)_a w(3,q)_b ]
    (link) (m / 24) C_ab [ dG_a w(5,p)_a w(1,q)_b + dG_b w(1,p)_a w(5,q)_b
                           + (dG_a + dG_b) w(3,p)_a w(3,q)_b ]

with w(5,1) = -(alpha^3 - 3 alpha) phi / sigma^4 and w(5,2) = 2 w(4,1).
Exact law, odd-eps d^2 response: cov(0,1) exact +3.5281e-3, v32 0, q31 only
+2.5001e-3, q31+link +3.5277e-3; kappa3(0,0,1) exact -0.16210, v32 -0.02023,
q31 only -0.21092, q31+link -0.16209. O(n^2) per layer, no new product.
The public v17 carries only the (3,1) rows (`wk431`), which overshoot.
"""

from __future__ import annotations

import hashlib
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)

_PATCH = '''    if _REP_MODE and not last_layer:
        # STAGE 1b: first-order kappa4 (x C) completion of the bivariate moment
        # slices -- derivation in `local_sim/s5_build_rep.py`.
        _li_r = layer_index - 1
        _lam_r = float(_K4_LAM[_li_r]) if 0 <= _li_r < len(_K4_LAM) else 0.0
        _ph_r = fnp.exp(alpha * alpha * (-0.5)) * 0.3989422804014327
        _s4_r = sigma * sigma * sigma * sigma
        _w5 = {1: ((alpha * alpha - 3.0) * alpha * _ph_r / _s4_r) * (-1.0),
               2: w[(4, 1)] * 2.0}
        for (_p, _q) in ((1, 1), (2, 1), (2, 2)):
            _add = None
            if "q31" in _REP_MODE:
                _t = ((w[(3, _p)][:, None] * w[(1, _q)][None, :]
                       + w[(1, _p)][:, None] * w[(3, _q)][None, :]) * C11)
                _add = _t * (metric * _lam_r / 12.0)
            if "link" in _REP_MODE:
                _t2 = (((dG * _w5[_p])[:, None] * w[(1, _q)][None, :]
                        + w[(1, _p)][:, None] * (dG * _w5[_q])[None, :]
                        + (dG[:, None] + dG[None, :]) * (w[(3, _p)][:, None] * w[(3, _q)][None, :]))
                       * C11) * (metric / 24.0)
                _add = _t2 if _add is None else _add + _t2
            if _add is not None:
                pK[(_p, _q)] = pK[(_p, _q)] + (_add if _p != _q else (_add + _add.T) * 0.5)

'''

ANCHOR = "    # ---- the (1,1,1) block's repeated part -------------------------------"


def build(text, mode=("q31", "link")):
    if text.count(ANCHOR) != 1:
        raise SystemExit("rep anchor not unique")
    text = text.replace(ANCHOR, _PATCH + ANCHOR, 1)
    a = "_P2_SEPARABLE = True\n"
    if text.count(a) != 1:
        raise SystemExit("constants anchor")
    text = text.replace(a, a + "\n#: STAGE 1b kappa4 (x C) bivariate completion; () disables.\n"
                        "_REP_MODE = %r\n" % (tuple(mode),), 1)
    c = '''    return base + thin'''
    if text.count(c) != 1:
        raise SystemExit("cost anchor")
    text = text.replace(c, '''    if _REP_MODE:
        thin += 60 * n * n * depth                  # stage 1b, O(n^2) elementwise, over-charged
    return base + thin''', 1)
    return text


ARMS = {
    "estimator_k3_v34.py": ("estimator_k3_v32.py", ("q31", "link")),
    "estimator_k3_v34_q31.py": ("estimator_k3_v32.py", ("q31",)),
    "estimator_k3_v34_dense.py": ("estimator_k3_v32_dense.py", ("q31", "link")),
}


def emit():
    for name, (base, mode) in ARMS.items():
        with open(os.path.join(_ROOT, base), encoding="utf-8") as fh:
            t = build(fh.read(), mode)
        t = ('"""%s: %s + stage-1b bivariate kappa4 (x C) completion %r. GENERATED by '
             'local_sim/s5_build_rep.py; do not edit."""\n' % (name, base, mode)) + t
        with open(os.path.join(_ROOT, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(t)
        print("  wrote %-28s sha256 %s" % (name, hashlib.sha256(t.encode()).hexdigest()[:16]))


if __name__ == "__main__":
    emit()
