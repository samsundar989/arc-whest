"""Truth-free positive and refusal checks for the compact one-row gate."""

from __future__ import annotations

import argparse
import json
import os
import shutil
import tempfile

import lifecycle_eval as le
import p2_build_k4_arms as builder
import p2_compact_arm_gate as gate


HERE = os.path.dirname(os.path.abspath(__file__))


def run():
    rows = []

    exact = os.path.join(builder.ARMS_DIR, "arm_exact.py")
    positive = gate.run(exact, seed=40910007000, width=8, depth=4)
    binding = positive["source_binding"]
    rows.append({
        "check": "positive gate binds executed registered bytes",
        "pass": bool(binding["exact_registered_regeneration"]
                     and positive["candidate_sha256"]
                     == binding["lifecycle_candidate_sha256"]
                     == binding["closing_candidate_sha256"]
                     and positive["operation_group_parity"]["flops_exact"]
                     and positive["operation_group_parity"]["calls_exact"]),
    })

    old_dir = builder.ARMS_DIR
    with tempfile.TemporaryDirectory(prefix="compact-arm-gate-stale-",
                                     dir=os.path.dirname(HERE)) as tmp:
        try:
            builder.ARMS_DIR = tmp
            stale = os.path.join(tmp, "arm_exact.py")
            shutil.copyfile(exact, stale)
            with open(stale, "a", encoding="utf-8") as fh:
                fh.write("\n# unregistered semantic no-op\n")
            try:
                gate.run(stale, seed=1, width=4, depth=2)
                refused = False
            except ValueError as exc:
                refused = "exact registered regeneration" in str(exc)
        finally:
            builder.ARMS_DIR = old_dir
    rows.append({"check": "stale generated bytes refuse before lifecycle",
                 "pass": refused})

    original_evaluate = gate.le.evaluate
    calls = []

    def misbind(*args, **kwargs):
        calls.append(True)
        result_rows, provenance = original_evaluate(*args, **kwargs)
        provenance = dict(provenance)
        provenance["candidate_sha256"] = "0" * 64
        return result_rows, provenance

    gate.le.evaluate = misbind
    try:
        try:
            gate.run(exact, seed=2, width=4, depth=2)
            misbound_refused = False
        except RuntimeError as exc:
            misbound_refused = "bytes changed" in str(exc)
    finally:
        gate.le.evaluate = original_evaluate
    rows.append({"check": "misbound lifecycle provenance refuses publication",
                 "pass": bool(calls and misbound_refused)})

    try:
        le.evaluate(exact, [1, 2], [[0.0] * 4, [0.0] * 4],
                    spec=le.LifecycleSpec(width=4, depth=2),
                    operation_logs_out=[])
        multi_refused = False
    except ValueError as exc:
        multi_refused = "one-row audits" in str(exc)
    rows.append({"check": "multi-row operation-log retention is refused",
                 "pass": multi_refused})

    failed = [row for row in rows if not row["pass"]]
    return {"kind": "label-free compact arm gate conformance",
            "checks": rows, "n_checks": len(rows),
            "n_failed": len(failed), "pass": not failed}


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--json", default="")
    args = parser.parse_args(argv)
    result = run()
    for row in result["checks"]:
        print("%-58s %s" %
              (row["check"], "PASS" if row["pass"] else "FAIL"))
    if args.json:
        with open(args.json, "w", encoding="utf-8", newline="\n") as fh:
            json.dump(result, fh, indent=2, sort_keys=True)
            fh.write("\n")
    return 0 if result["pass"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
