"""Asserted source generator for the registered four global own-fit controls.

Base: own PAIR+Q complete program, with its own lambda initializer. This module
does not fit parameters or read labels. Default controls reproduce the base.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "estimator_k3_v40_pairq.py"
BASE_SHA256 = "7e5c24d33c279199c5284e6997157f98772a3ddb8bee753baf219628721cc4d5"
BOUNDS = ((0.0, 1.5), (0.5, 1.5), (-0.5, 0.5), (0.5, 1.5))


def _once(src, old, new, label):
    count = src.count(old)
    if count != 1:
        raise ValueError(f"{label}: expected one anchor, found {count}")
    return src.replace(old, new, 1)


def build(src, theta_fam=1.0, s_lam=1.0, t_lam=0.0, s_feed=1.0):
    values = (float(theta_fam), float(s_lam), float(t_lam), float(s_feed))
    if not all(lo <= x <= hi for x, (lo, hi) in zip(values, BOUNDS)):
        raise ValueError("own-fit parameter outside registered range")
    if "_CLOSURE_SCOPE = 'all'" not in src or "_PROTECT_FEED = False" not in src:
        raise ValueError("expected own PAIR+Q closure with unprotected feed")
    flags = ("# Registered own global fit controls; no reference lambda or mask.\n"
             "_OWN_THETA_FAM = %r\n_OWN_S_LAM = %r\n_OWN_T_LAM = %r\n"
             "_OWN_S_FEED = %r\n\n" % values)
    src = _once(src, "_K4_PERNEURON = True", flags + "_K4_PERNEURON = True", "flags")
    src = _once(src, "def _closure_apply(pK, cc, sigma, alpha, blocks, off_mask, last_layer, dtype):",
                "def _own_extra(x):\n"
                "    return x if _OWN_THETA_FAM == 1.0 else x * _OWN_THETA_FAM\n\n\n"
                "def _closure_apply(pK, cc, sigma, alpha, blocks, off_mask, last_layer, dtype):",
                "family helper")
    src = _once(src, "pK[(p,)] = pK[(p,)] + X",
                "pK[(p,)] = pK[(p,)] + _own_extra(X)", "univariate family")
    src = _once(src, "pK[out] = pK[out] + X * off_mask",
                "pK[out] = pK[out] + _own_extra(X) * off_mask", "bivariate family")
    lam_fun = '''def _own_lambda(i, depth):
    """Own lambda initializer at source layer i, with registered depth tilt."""
    base = _K4_LAM[i] if 0 <= i < len(_K4_LAM) else 0.0
    if _OWN_S_LAM == 1.0 and _OWN_T_LAM == 0.0:
        return base
    phase = (float(i) / float(depth - 1) - 0.5) if depth > 1 else 0.0
    return base * _OWN_S_LAM * (1.0 + _OWN_T_LAM * phase)


'''
    src = _once(src, "def _layer(W, state, table, dtype, const, init_scale, last_layer, gens,",
                lam_fun + "def _layer(W, state, table, dtype, const, init_scale, last_layer, gens,",
                "lambda helper")
    src = _once(src, "           layer_index=0):", "           layer_index=0, depth=1):", "depth argument")
    src = _once(src, "_K4_LAM[_li] if 0 <= _li < len(_K4_LAM) else 0.0",
                "_own_lambda(_li, depth)", "carried lambda")
    src = _once(src, "float(_K4_LAM[_li_h]) if 0 <= _li_h < len(_K4_LAM) else 0.0",
                "float(_own_lambda(_li_h, depth))", "birth lambda")
    # Scale the birth coefficients before both the represented newborn and
    # its repeated-index compensation consume them. At the default, preserve
    # the existing arithmetic exactly.
    src = _once(src, "            resid = S21 - S_sep\n            if _HUB_COMPENSATE:",
                "            if _OWN_S_FEED != 1.0:\n"
                "                cA = cA * _OWN_S_FEED\n"
                "                cB = cB * _OWN_S_FEED\n"
                "            resid = S21 - S_sep\n            if _HUB_COMPENSATE:",
                "coherent birth feed")
    old = "                           layer_index=l)"
    if src.count(old) != 2:
        raise ValueError(f"depth calls: expected two anchors, found {src.count(old)}")
    src = src.replace(old, "                           layer_index=l, depth=depth)")
    return src


def emit(output, **params):
    raw = BASE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != BASE_SHA256:
        raise ValueError("own PAIR+Q base bytes changed")
    src = build(raw.decode("utf-8"), **params)
    hdr = (f"OWN-FIT CONTROL ARM, generated by local_sim/s14_own_fit_controls.py.\n"
           f"Base: {BASE.name}, sha256 {hashlib.sha256(raw).hexdigest()}.\n"
           f"Parameters: {params}. No accuracy decision or submission approval.\n\n")
    i = src.find('"""')
    if i < 0:
        raise ValueError("base has no module docstring")
    src = src[:i+3] + hdr + src[i+3:]
    output.write_text(src, encoding="utf-8", newline="\n")
    return hashlib.sha256(output.read_bytes()).hexdigest()


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", type=Path, required=True)
    ap.add_argument("--theta-fam", type=float, default=1.0)
    ap.add_argument("--s-lam", type=float, default=1.0)
    ap.add_argument("--t-lam", type=float, default=0.0)
    ap.add_argument("--s-feed", type=float, default=1.0)
    a = ap.parse_args()
    print(emit(a.output, theta_fam=a.theta_fam, s_lam=a.s_lam,
               t_lam=a.t_lam, s_feed=a.s_feed))
