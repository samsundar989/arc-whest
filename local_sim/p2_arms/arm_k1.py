"""P2-CP1 arm: k1.

Means and diagonal variances only -- the cheap end of the ladder. No
cross-neuron state, so `diag(W^T Sigma W)` collapses to `(W*W)^T v` and the
whole arm is O(n^2 L) instead of O(n^3 L).

GENERATED by local_sim/p2_build_arms.py -- do not edit this file. Edit the
generator, which holds the shared math once so the arms cannot drift apart.

Grader-legal: imports only flopscope, flopscope.numpy and whestbench. Never
mutates a grader array. Shape-generic. Deterministic given the network.
"""

import flopscope as flops
import flopscope.numpy as fnp
from whestbench import MLP, BaseEstimator

_INV_SQRT_2PI = 0.3989422804014327
_ORDER = 0
_DTYPE = fnp.float64


class Estimator(BaseEstimator):
    """k1: Gaussian closure, post-ReLU covariance at Price order 0."""

    def setup(self, context) -> None:
        # Nothing to build. A carrier that constructs a point set here is what
        # the setup window exists to price; this family does not.
        return None

    def predict(self, mlp: MLP, budget: int) -> fnp.ndarray:
        w = [x.astype(_DTYPE) for x in mlp.weights]
        rows = self._closure(w, mlp.width, len(w))
        # Layer 1 is exact and cheap: z_1 = x W_1 is EXACTLY Gaussian with zero
        # mean, so E[ReLU] = ||W_1[:, j]|| / sqrt(2 pi). The closure already
        # reproduces this analytically -- alpha = 0, Phi = 1/2, phi = 1/sqrt(2pi)
        # -- but through a matmul diagonal rather than a column norm, so the two
        # differ at 1e-16. Taking the closed form is the numerically better of
        # two exact expressions, and it is what the shipped estimator does.
        var0 = (w[0] * w[0]).sum(axis=0, dtype=fnp.float64)
        exact = fnp.sqrt(var0) * _INV_SQRT_2PI
        return fnp.concatenate(
            [fnp.reshape(exact.astype(rows.dtype), (1, mlp.width)), rows[1:]],
            axis=0,
        )

    def _closure(self, w, width, depth):
        """K1: means and DIAGONAL variances only. No cross-neuron state.

        Each layer needs only `diag(W^T Sigma W)`, and with Sigma diagonal that
        is `(W * W)^T v` -- one O(n^2) product instead of two O(n^3) matmuls.
        The whole arm is therefore ~n cheaper than any K2 spelling, which is the
        point of having it in the ladder.
        """
        mu = fnp.zeros(width, dtype=_DTYPE)
        var = fnp.ones(width, dtype=_DTYPE)
        rows = []
        for k in range(depth):
            wk = w[k]
            mu_pre = wk.T @ mu
            var_pre = fnp.maximum((wk * wk).T @ var, 1e-12)
            sig = fnp.sqrt(var_pre)
            alpha = mu_pre / sig
            Phi = flops.stats.norm.cdf(alpha)
            phi = flops.stats.norm.pdf(alpha)
            mu = mu_pre * Phi + sig * phi
            ez2 = (mu_pre * mu_pre + var_pre) * Phi + mu_pre * sig * phi
            var = fnp.maximum(ez2 - mu * mu, 0.0)
            rows.append(mu)
        return fnp.stack(rows, axis=0)
