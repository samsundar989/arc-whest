"""P2-CP1 sampling arm: sample_orth.

Orthogonal Monte Carlo at the floor budget, matched to sample_iid_floor on
ROWS so the comparison isolates variance reduction from budget. The QR cost
is charged, not ignored.

GENERATED by local_sim/p2_build_sampling_arms.py -- do not edit. Edit the
generator, which holds the shared budget arithmetic once.

Grader-legal: flopscope, flopscope.numpy, whestbench, stdlib only. Never mutates
a grader array. Shape-generic. Randomness derives from `mlp.seed` alone.
"""

import flopscope as flops
import flopscope.numpy as fnp
from whestbench import MLP, BaseEstimator

_INV_SQRT_2PI = 0.3989422804014327

#: MEASURED at 1024 x 16 under flopscope 0.10 and 0.12 (identical): one sample
#: through all layers costs 33,587,196 FLOPs against the 2*d*w^2 = 33,554,432
#: identity, i.e. 0.10% overhead. Expressed as a ratio so it stays shape-generic.
_OVERHEAD = 1.0011

#: Fraction of the budget the arm aims to spend. NOT a tuned constant: exceeding
#: B raises BudgetExhaustedError, which the grader scores as a FAILURE -- zeroed
#: predictions AND multiplier 1.0, about 5x worse than simply spending B. The
#: margin buys nothing except never touching that cliff.
_TARGET_CB = 0.1

#: Rows per chunk. flopscope bills the release of large temporaries as residual
#: wall time at ~100-120 us/op against ~6-8 us when release is deferred
#: (docs/GOTCHAS.md, forum 18101), so the rule is FEWER, LARGER ops. 4096 rows
#: at width 1024 in float32 is 16.8 MB per activation -- comfortably inside the
#: 64 GB package-default RLIMIT_AS while keeping the op count at N/4096.
_CHUNK = 4096


class Estimator(BaseEstimator):
    """sample_orth."""

    def setup(self, context) -> None:
        return None

    def _n_samples(self, width, depth, budget):
        """Largest N that fits `_TARGET_CB * budget`, sized from MEASURED cost."""
        per = 2.0 * depth * width * width * _OVERHEAD
        n = int(_TARGET_CB * float(budget) / per)
        return max(n, 1)

    def _exact_first_layer(self, w0):
        var = (w0 * w0).sum(axis=0, dtype=fnp.float64)
        return fnp.sqrt(var) * _INV_SQRT_2PI

    def _accumulate(self, w, x):
        """Forward one chunk, returning the per-layer column sums."""
        h = x
        out = []
        for wk in w:
            h = fnp.maximum(h @ wk, 0.0)
            out.append(fnp.sum(h, axis=0, dtype=fnp.float64))
        return out

    def _draw(self, rng, m, width, k):
        """Orthogonal Monte Carlo: rows of a random orthogonal basis, rescaled.

        Choromanski et al. (2019). Take `Q` Haar-orthogonal, then `r_i * Q[i, :]`
        with `r_i` chi-distributed with `width` degrees of freedom has exactly the
        N(0, I) marginal, while the rows are exactly orthogonal instead of
        approximately so. The variance reduction comes from removing the
        realised correlation between directions, which iid sampling leaves in.

        A basis supplies `width` rows, so a chunk of `m` rows uses
        `ceil(m / width)` bases. `qr` on a 1024 x 1024 float32 costs 2.86e9 =
        0.0013 B, so 16 bases (16,384 rows) cost 2% of the budget on top of the
        propagation -- charged, not ignored.
        """
        cols = []
        rows_left = m
        while rows_left > 0:
            g = rng.standard_normal((width, width), dtype=fnp.float32)
            q, r = fnp.linalg.qr(g)
            # Sign-fix so the basis is Haar rather than QR-implementation
            # dependent: without it the sign convention of the LAPACK routine
            # leaks into the point set.
            q = q * fnp.sign(fnp.diagonal(r))
            chi = fnp.sqrt(fnp.sum(
                rng.standard_normal((width, width), dtype=fnp.float32) ** 2,
                axis=1))
            block = q * fnp.reshape(chi, (width, 1))
            take = min(rows_left, width)
            cols.append(block[:take])
            rows_left -= take
        return fnp.concatenate(cols, axis=0) if len(cols) > 1 else cols[0]

    def predict(self, mlp: MLP, budget: int) -> fnp.ndarray:
        width = mlp.width
        depth = len(mlp.weights)
        w = [x.astype(fnp.float32) for x in mlp.weights]
        n = self._n_samples(width, depth, budget)
        rng = fnp.random.default_rng(int(mlp.seed))

        totals = None
        done = 0
        while done < n:
            m = min(_CHUNK, n - done)
            x = self._draw(rng, m, width, done)
            part = self._accumulate(w, x)
            totals = part if totals is None else [a + b for a, b in zip(totals, part)]
            done += m

        rows = [t / float(n) for t in totals]
        rows[0] = self._exact_first_layer(w[0].astype(fnp.float64))
        return fnp.stack(rows, axis=0)
