"""Emit the four compact all-history Stage-2 mechanism arms."""

from __future__ import annotations

import argparse
import ast
import hashlib
import math
import os


_HERE = os.path.dirname(os.path.abspath(__file__))
ARMS_DIR = os.path.join(_HERE, "p2_arms")
SOURCE = os.path.join(_HERE, "p2_compact_candidate_template.py")
DEFAULT_LAM = 1.0 / 3.0

ARMS = (
    ("exact", False, False,
     "Compact K4-off control; consumers and induced K3 births disabled."),
    ("coherent", True, True,
     "Compact coherent K4 consumers and induced K3 births."),
    ("consumers_only", True, False,
     "Compact mechanism arm with K4 consumers only."),
    ("births_only", False, True,
     "Compact mechanism arm with induced K3 births only."),
)

_MARKERS = (
    ("_K4_CONSUMERS = False  # __K4_CONSUMERS__", "_K4_CONSUMERS = {consumers}"),
    ("_K4_BIRTHS = False  # __K4_BIRTHS__", "_K4_BIRTHS = {births}"),
    ("_K4_ACTIVE = False  # __K4_ACTIVE__", "_K4_ACTIVE = {active}"),
    ("_K4_LAM = 0.33333333333333331  # __K4_LAM__", "_K4_LAM = {lam}"),
)


def _source():
    raw = open(SOURCE, "rb").read()
    return raw.decode("utf-8"), hashlib.sha256(raw).hexdigest()


def build(name, consumers, births, blurb, src, src_sha, lam):
    """Render one arm, refusing a missing or duplicated template marker."""
    lam = float(lam)
    if not math.isfinite(lam):
        raise ValueError("lam must be finite")
    values = {"consumers": repr(bool(consumers)),
              "births": repr(bool(births)),
              "active": repr(bool(consumers or births)),
              "lam": "%.17g" % lam}
    body = src
    for marker, replacement in _MARKERS:
        count = body.count(marker)
        if count != 1:
            raise RuntimeError("%s: marker %r expected once, found %d" %
                               (name, marker, count))
        body = body.replace(marker, replacement.format(**values), 1)
    if "__K4_" in body:
        raise RuntimeError("%s: unresolved K4 template marker" % name)

    tree = ast.parse(body, filename=os.path.basename(SOURCE))
    first = tree.body[0]
    if not (isinstance(first, ast.Expr)
            and isinstance(first.value, ast.Constant)
            and isinstance(first.value.value, str)):
        raise RuntimeError("template must begin with a module docstring")
    lines = body.splitlines(keepends=True)
    body = "".join(lines[first.end_lineno:]).lstrip("\n")
    header = ('"""Generated compact Stage-2 K4 arm: %s.\n\n%s\n'
              'Template sha256 %s. Generated by '
              'local_sim/p2_build_k4_arms.py.\n'
              'No research labels or fitted observations were read.\n"""\n\n'
              % (name, blurb, src_sha))
    rendered = header + body
    ast.parse(rendered, filename="arm_%s.py" % name)
    return rendered


def emit(lam=DEFAULT_LAM):
    src, sha = _source()
    os.makedirs(ARMS_DIR, exist_ok=True)
    for name, consumers, births, blurb in ARMS:
        rendered = build(name, consumers, births, blurb, src, sha, lam)
        path = os.path.join(ARMS_DIR, "arm_%s.py" % name)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(rendered)
        print("wrote %-24s consumers=%-5s births=%-5s bytes=%d" %
              (os.path.basename(path), consumers, births,
               len(rendered.encode("utf-8"))))
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--emit", action="store_true")
    parser.add_argument("--lam", type=float, default=DEFAULT_LAM)
    args = parser.parse_args(argv)
    if args.emit:
        return emit(args.lam)
    parser.print_help()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
