"""Generate the P2-CP1 comparison arms as SELF-CONTAINED, grader-legal files.

P2-CP1 compares families, and every arm has to be scored through one canonical
evaluator (`local_sim/lifecycle_eval.py`), which loads a candidate FILE with an
`Estimator` class. Two ways to get six such files: a shared module the arms
import, or generation. Generation wins here for three reasons:

  * a shared import is **not grader-legal** (hard rule 1 allows only flopscope,
    flopscope.numpy, whestbench and stdlib), so a lab arm built that way would
    have to be re-ported before it could ever be a candidate. These files can be
    dropped in as `estimator.py` unchanged;
  * `setup()` timing and module-load cost are measured on the real thing;
  * the shared math exists **once**, here, so the arms cannot drift apart. That
    matters more than it sounds: the whole point of the ladder is that the arms
    differ in exactly one place.

## The ladder, and why it is the ladder

Every arm propagates the same state through the same Gaussian closure and differs
only in the **post-ReLU covariance map**. Write the pre-activation as
`z ~ N(mu, Sigma)`, `v = diag(Sigma)`, `sigma = sqrt(v)`, `alpha = mu / sigma`.

The mean and the variance are **exact given the Gaussian model**:

    m   = mu * Phi(alpha) + sigma * phi(alpha)
    E[R^2] = (mu^2 + v) * Phi(alpha) + mu * sigma * phi(alpha)

Only the OFF-DIAGONAL covariance is approximated, and there the exact answer is a
convergent series. For jointly Gaussian `X, Y` with correlation `r`, Price's
theorem gives

    Cov[f(X), g(Y)] = sum_{k>=1} (r^k / k!) * a_k * b_k,
    a_k = E[ f^{(k)} ]

and for `f(x) = ReLU(x)` on `X ~ N(mu, sigma^2)`, writing `g(u) = ReLU(u + alpha)`
so that `f(X) = sigma * g(U)`:

    a_1 = Phi(alpha)
    a_k = He_{k-2}(-alpha) * phi(alpha),   k >= 2

with `He` the probabilists' Hermite polynomials (`He_0 = 1`, `He_1(x) = x`,
`He_2(x) = x^2 - 1`, `He_3(x) = x^3 - 3x`). So

    Cov[ReLU(z_i), ReLU(z_j)] = sum_{k>=1} c_ij^k / (k! * (sigma_i sigma_j)^(k-1))
                                 * a_k(alpha_i) * a_k(alpha_j)

**Order 1 is exactly the spelling the shipped estimator uses**:
`c_ij * Phi_i * Phi_j`. That is not an insight about our code, it is a
*derivation* of it -- the shipped closure is the first-order Price truncation,
and it has been the first-order truncation since v0.

**Each additional order costs O(n^2) per layer.** The propagation itself is
`W^T Sigma W`, which is O(n^3). At n = 1024 an extra order is ~1/1000 of the
layer's cost -- so "augmented K2" here is *almost free*, and the ladder measures
what that buys.

**What the ladder can and cannot isolate.** The Gaussian closure has two error
sources: (a) the post-ReLU state is not Gaussian, so modelling layer k+1's input
as Gaussian is wrong; (b) even granting (a), the post-ReLU covariance map is
truncated. **The Hermite ladder removes (b) entirely** as the order grows, so the
limit of the ladder is the exact-Gaussian-closure floor, and whatever remains is
(a) -- which is what a K3/Edgeworth correction has to attack. A ladder that
plateaus is telling you the remaining error is (a), and that is the single most
useful thing P2-CP1 can learn.

Layer 1 is a free consistency check: `z_1 = x W_1` is **exactly** Gaussian, so at
layer 1 a high-order arm's covariance is exact, not approximate.

## Arms

    k1        mean + DIAGONAL variance only. No off-diagonal state at all.
              O(n^2 L) -- the cheap end of the ladder.
    k2p1      full covariance, Price order 1. == the shipped `_analytic_only`.
    k2p2      ... order 2      (adds  c^2 / (2 s_i s_j) * phi_i phi_j)
    k2p3      ... order 3
    k2p4      ... order 4
    k2p6      ... order 6
    k2p1_f32  order 1 in float32 -- the cost lever, since flopscope meters
              float64 at rate 2.0

Sampling arms (Sobol, 32 orthogonal signed bases) are generated by
`p2_build_sampling_arms.py`; they share no math with these.

Run:  uv run python local_sim/p2_build_arms.py
      uv run python local_sim/p2_build_arms.py --check   (regenerate + diff only)
"""

from __future__ import annotations

import argparse
import hashlib
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
ARMS = os.path.join(_HERE, "p2_arms")

HEADER = '''"""P2-CP1 arm: {name}.

{blurb}

GENERATED by local_sim/p2_build_arms.py -- do not edit this file. Edit the
generator, which holds the shared math once so the arms cannot drift apart.

Grader-legal: imports only flopscope, flopscope.numpy and whestbench. Never
mutates a grader array. Shape-generic. Deterministic given the network.
"""

import flopscope as flops
import flopscope.numpy as fnp
from whestbench import MLP, BaseEstimator

_INV_SQRT_2PI = 0.3989422804014327
_ORDER = {order}
_DTYPE = fnp.{dtype}


class Estimator(BaseEstimator):
    """{name}: Gaussian closure, post-ReLU covariance at Price order {order}."""

    def setup(self, context) -> None:
        # Nothing to build. A carrier that constructs a point set here is what
        # the setup window exists to price; this family does not.
        return None

    def predict(self, mlp: MLP, budget: int) -> fnp.ndarray:
        w = [x.astype(_DTYPE) for x in mlp.weights]
        rows = self._closure(w, mlp.width, len(w))
        # Layer 1 is exact and cheap: z_1 = x W_1 is EXACTLY Gaussian with zero
        # mean, so E[ReLU] = ||W_1[:, j]|| / sqrt(2 pi). The closure already
        # reproduces this analytically -- alpha = 0, Phi = 1/2, phi = 1/sqrt(2pi)
        # -- but through a matmul diagonal rather than a column norm, so the two
        # differ at 1e-16. Taking the closed form is the numerically better of
        # two exact expressions, and it is what the shipped estimator does.
        var0 = (w[0] * w[0]).sum(axis=0, dtype=fnp.float64)
        exact = fnp.sqrt(var0) * _INV_SQRT_2PI
        return fnp.concatenate(
            [fnp.reshape(exact.astype(rows.dtype), (1, mlp.width)), rows[1:]],
            axis=0,
        )
'''

CLOSURE_DIAG = '''
    def _closure(self, w, width, depth):
        """K1: means and DIAGONAL variances only. No cross-neuron state.

        Each layer needs only `diag(W^T Sigma W)`, and with Sigma diagonal that
        is `(W * W)^T v` -- one O(n^2) product instead of two O(n^3) matmuls.
        The whole arm is therefore ~n cheaper than any K2 spelling, which is the
        point of having it in the ladder.
        """
        mu = fnp.zeros(width, dtype=_DTYPE)
        var = fnp.ones(width, dtype=_DTYPE)
        rows = []
        for k in range(depth):
            wk = w[k]
            mu_pre = wk.T @ mu
            var_pre = fnp.maximum((wk * wk).T @ var, 1e-12)
            sig = fnp.sqrt(var_pre)
            alpha = mu_pre / sig
            Phi = flops.stats.norm.cdf(alpha)
            phi = flops.stats.norm.pdf(alpha)
            mu = mu_pre * Phi + sig * phi
            ez2 = (mu_pre * mu_pre + var_pre) * Phi + mu_pre * sig * phi
            var = fnp.maximum(ez2 - mu * mu, 0.0)
            rows.append(mu)
        return fnp.stack(rows, axis=0)
'''

CLOSURE_FULL = '''
    def _closure(self, w, width, depth):
        """K2: full covariance, post-ReLU map truncated at Price order _ORDER.

        Off-diagonal:

            Cov[R_i, R_j] = sum_{{k>=1}} c^k / (k! (s_i s_j)^(k-1)) a_k(al_i) a_k(al_j)
            a_1 = Phi(al),   a_k = He_{{k-2}}(-al) phi(al)

        Order 1 alone is `c * Phi_i * Phi_j`, which is the shipped estimator's
        spelling. The diagonal is NEVER taken from the series -- at r = 1 it
        converges slowly and the closed form is exact -- so it is written in
        directly, exactly as the first-order code already did.
        """
        mu = fnp.zeros(width, dtype=_DTYPE)
        cov = fnp.eye(width, dtype=_DTYPE)
        off = fnp.ones((width, width), dtype=_DTYPE) - fnp.eye(width, dtype=_DTYPE)
        rows = []
        for k in range(depth):
            wk = w[k]
            mu_pre = wk.T @ mu
            cov_pre = wk.T @ cov @ wk
            var_pre = fnp.maximum(fnp.diagonal(cov_pre), 1e-12)
            sig = fnp.sqrt(var_pre)
            alpha = mu_pre / sig
            Phi = flops.stats.norm.cdf(alpha)
            phi = flops.stats.norm.pdf(alpha)

            mu = mu_pre * Phi + sig * phi
            ez2 = (mu_pre * mu_pre + var_pre) * Phi + mu_pre * sig * phi
            var = fnp.maximum(ez2 - mu * mu, 0.0)

            # Written in the SHIPPED estimator's exact operation order, so the
            # order-1 rung is BITWISE the control rather than a re-derivation
            # that happens to be close. Float addition is not associative;
            # `outer(Phi,Phi) * cov_pre * off` and `outer(Phi,Phi) * (cov_pre *
            # off)` differ in the last bit, and a control that differs from the
            # thing it controls in the last bit is not a control.
            acc = fnp.outer(Phi, Phi) * cov_pre * off
{orders}
            cov = acc + fnp.diag(var)
            rows.append(mu)
        return fnp.stack(rows, axis=0)
'''

# a_k(alpha) = He_{k-2}(-alpha) * phi(alpha), written out so no Hermite
# recursion runs inside the budgeted path.
A_K = {
    2: "phi",
    3: "(-alpha) * phi",
    4: "(alpha * alpha - 1.0) * phi",
    5: "(-(alpha * alpha * alpha) + 3.0 * alpha) * phi",
    6: "(alpha * alpha * alpha * alpha - 6.0 * (alpha * alpha) + 3.0) * phi",
}
FACT = {2: 2.0, 3: 6.0, 4: 24.0, 5: 120.0, 6: 720.0}


def _order_block(order: int) -> str:
    """Emit orders 2..order of the Price series."""
    if order < 2:
        return ""
    out = [
        "            # Price/Hermite orders 2..%d. `cs` is the running"
        " c^k/(s_i s_j)^(k-1)," % order,
        "            # so each extra order is ONE elementwise multiply on an"
        " n x n array --",
        "            # O(n^2) against the O(n^3) propagation above.",
        "            inv_ss = fnp.outer(1.0 / sig, 1.0 / sig)",
        "            c = cov_pre * off",
        "            cs = c",
    ]
    for k in range(2, order + 1):
        out.append(f"            cs = cs * c * inv_ss")
        out.append(f"            a{k} = {A_K[k]}")
        out.append(f"            acc = acc + (cs / {FACT[k]}) * fnp.outer(a{k}, a{k})")
    return "\n".join(out)


SPECS = [
    ("k1", 0, "float64",
     "Means and diagonal variances only -- the cheap end of the ladder. No\n"
     "cross-neuron state, so `diag(W^T Sigma W)` collapses to `(W*W)^T v` and the\n"
     "whole arm is O(n^2 L) instead of O(n^3 L)."),
    ("k2p1", 1, "float64",
     "Full covariance, Price order 1. This is EXACTLY the shipped estimator's\n"
     "`_analytic_only` spelling (`c_ij * Phi_i * Phi_j`), and it is the control\n"
     "the rest of the ladder is measured against."),
    ("k2p2", 2, "float64", "Full covariance, Price orders 1-2."),
    ("k2p3", 3, "float64", "Full covariance, Price orders 1-3."),
    ("k2p4", 4, "float64", "Full covariance, Price orders 1-4."),
    ("k2p6", 6, "float64",
     "Full covariance, Price orders 1-6. The deep end: if the ladder has\n"
     "plateaued by here, the remaining error is the closure's non-Gaussianity\n"
     "(source (a)), not its covariance map (source (b)) -- which is the single\n"
     "most useful thing P2-CP1 can establish."),
    ("k2p1_f32", 1, "float32",
     "Price order 1 in float32. flopscope meters float64 at rate 2.0, so this is\n"
     "the cost lever: same math, half the counted FLOPs. Whether the precision\n"
     "costs accuracy is exactly what the arm measures."),
]


def build() -> dict:
    os.makedirs(ARMS, exist_ok=True)
    init = os.path.join(ARMS, "__init__.py")
    if not os.path.exists(init):
        with open(init, "w", encoding="utf-8") as fh:
            fh.write("# generated arm package; see local_sim/p2_build_arms.py\n")
    out = {}
    for name, order, dtype, blurb in SPECS:
        body = (CLOSURE_DIAG if order == 0
                else CLOSURE_FULL.format(orders=_order_block(order)))
        src = HEADER.format(name=name, order=order, dtype=dtype, blurb=blurb) + body
        path = os.path.join(ARMS, f"arm_{name}.py")
        out[name] = (path, src)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="regenerate and report drift instead of writing")
    a = ap.parse_args()

    built = build()
    drift = []
    print("=" * 78)
    print("P2-CP1 ARMS  --  generated, self-contained, grader-legal")
    print("=" * 78)
    for name, (path, src) in built.items():
        old = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as fh:
                old = fh.read()
        if a.check:
            if old != src:
                drift.append(name)
            state = "DRIFT" if old != src else "ok"
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(src)
            state = "written" if old != src else "unchanged"
        sha = hashlib.sha256(src.encode()).hexdigest()[:16]
        print(f"  {name:<12} {state:<10} {len(src):>6} bytes  sha256 {sha}  "
              f"{os.path.relpath(path, _ROOT)}")
    print("=" * 78)
    if drift:
        print(f"  DRIFT in {drift} -- an arm on disk differs from the generator.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
