"""Step 3 (handoff 2026-09-17): age-tier SHARED COORDINATES for old source lineages.

Generates arms from a frozen base (v32 or a v35 arm -- the tower code is identical)
by asserted patches. NOT the parked N1 merged core: every lineage keeps its own
factors; only the LEFT (current-layer) space of the old legs is shared.

REPRESENTATION
--------------
A lineage's legs `A_L` and `M` are `(n, n)` and only ever LEFT-multiplied after
birth (`W^T`, then a Wick column scale). Recent lineages stay exact. When a
lineage crosses the age gate its legs are written in one shared basis:

    A_L_b = Q FA_b,   M_b = Q FM_b,   Q (n, r) shared,  FA_b, FM_b (r, n) static.

Transport is then EXACT inside span(Q): one `(n,n)@(n,r)` a layer for all old
lineages, `Q <- col * (W^T Q)`. The ONLY approximation is at a JOIN, where the
crossing lineage is projected into a rebuilt basis:

    G  = A_j d(a) A_j^T + M_j d(m) M_j^T + Q Sg Q^T         (weighted Gram, never formed)
    Qn = qr(G Om)   [+ power passes]                        (range finder, rank r)
    FA_old <- (Qn^T Q) FA_old,  FA_j = Qn^T A_j,  Sg <- T Sg T^T + FA_j d(a) FA_j^T + ...

The weights `a_c = ||LA[:, c]||^2`, `m_c = ||LP[:, c]||^2` are the joiner's column
energies in THIS layer's `(2,1)` contraction `LA A_L^T + LP M^T`: the projection error
in that contraction is `sum_c a_c ||(I-P) A_c||^2 + m_c ||(I-P) M_c||^2`. `Sg` carries
the old lineages' weights from their own joins. The sketch `Om` is `Q` when old
lineages exist, else the r strongest weighted columns (norm-selected: deterministic
and permutation-equivariant, as `_p2_compress`).

CONSUMERS: the elementwise slice work needs the legs, so old legs are FORMED
(`Q @ FA`, `(n,r)@(r,k n)`) and concatenated in front of the recent ones; the two
dense contractions split: `(LA_old FA^T + LP_old FM^T) Q^T + LA_rec A_rec^T + LP_rec M_rec^T`.
Per old lineage a layer: ~4 products at `n^2 r` instead of 4 at `n^3`.

Everything else is per lineage and untouched: `Z`, `L`, `sb`, `eb`, `w2b`, hubs.
Confinement runs only when `gens is None` (the exact tower) and `r < n`
(`_SHARED_FORCE` allows `r = n` for the full-rank identity test).

Run:  uv run python local_sim/s7_build_shared.py --base estimator_k3_v32.py --emit
"""
