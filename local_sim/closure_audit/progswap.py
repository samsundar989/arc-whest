from fractions import Fraction

_HERE = os.path.dirname(os.path.abspath(__file__))
_LS = os.path.dirname(_HERE)
ROOT = os.path.dirname(_LS)
sys.path[:] = [q for q in sys.path if os.path.abspath(q or ".") not in (_HERE, _LS)] \
    + [ROOT, _LS, _HERE]

import canon  # noqa: E402

V17 = os.path.join(ROOT, "external", "504aldo", "estimators", "estimator_v17.py")
V32 = os.path.join(ROOT, "estimator_k3_v32.py")
DIAG = os.path.join(ROOT, "_diag")
TABLE_V17 = os.path.join(_LS, "closure", "closure_v17_complete.json")
TABLE_V32 = os.path.join(_LS, "closure", "closure_v32_only.json")
CHAIN4 = os.path.join(DIAG, "estimator_v17_v32prog.py")
#: the SAME rewrite with nothing dropped. It must reproduce native v17 bit for
#: bit, which is what proves the rewriting machinery itself is a no-op and that
#: any difference chain 4 shows is the program and not the transplant.
CHAIN4_ID = os.path.join(DIAG, "estimator_v17_identity.py")

BANNER = (
    "# ==========================================================================\n"
    "# DIAGNOSTIC COPY -- NEVER A RELEASE FILE, NEVER SUBMITTED, NEVER DESIGNATED\n"
    "# ==========================================================================\n"
    "# Generated by local_sim/closure_audit/progswap.py for the reciprocal\n"
    "# complete-program experiment (handoff 2026-09-17b section 1).\n"
    "# Parent:      %s\n"
    "#   sha256     %s\n"
    "# Program:     restricted to the canonical v32 term set (%s)\n"
    "#   sha256     %s\n"
    "# The ONLY change from the parent is which rows of TERM_SPECS execute.\n"
    "# Nothing here may enter a candidate, a submission or the write-up.\n"
    "# ==========================================================================\n"
)


def _records(terms):
    return canon.to_records(terms)


def _dump(path, payload):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(payload, fh, indent=1)
    return canon.sha256_file(path)


# --------------------------------------------------------------------------- #
# chain 4: v17 with its TERM_SPECS restricted to v32's canonical program
# --------------------------------------------------------------------------- #

def _v17_spec_rows(path):
    """Every executed TERM_SPECS row of live v17, with its canonical key(s).

    A single spec row can contribute to TWO canonical keys, because v17
    symmetrises the (1,1) and (2,2) outputs after the fact. The row is kept only
    if EVERY canonical key it contributes to is in the target program -- a row
    that would smuggle an unwanted oriented term in through symmetrisation is
    dropped, and `verify()` re-derives the emitted file's canonical program to
    prove the restriction landed.
    """
    src = open(path, encoding="utf-8").read()
    tree = ast.parse(src)
    pairs = canon._literal_assign(tree, "WICK_PAIRS")
    specs = {k: list(v) for k, v in canon._literal_assign(tree, "TERM_SPECS").items()}
    idx = pairs.index
    wk431 = [((1, 1), ("wk431", "ones2", idx((1, 1)), idx((3, 1)), 1.0 / 3.0)),
             ((2, 1), ("wk431", "ones2", idx((1, 2)), idx((3, 1)), 1.0 / 6.0)),
             ((2, 1), ("wk431", "ones2", idx((3, 2)), idx((1, 1)), 1.0 / 6.0)),
             ((2, 2), ("wk431", "ones2", idx((1, 2)), idx((3, 2)), 1.0 / 3.0))]
    for ip, s in wk431:
        if s not in specs[ip]:
            specs[ip].append(s)
    rows = []
    for ip, lst in specs.items():
        for pos, row in enumerate(lst):
            a, b, wl = row[0], row[1], row[2]
            rest = row[3:]
            factors = [canon._V17_BLOCK[x] for x in (a, b)
                       if canon._V17_BLOCK[x] is not None]
            if len(ip) == 1:
                kl, _pl = pairs[wl]
                derivs = [kl]
            else:
                wr = rest[0]
                (kl, _pl), (kr, _pr) = pairs[wl], pairs[wr]
                derivs = [kl, kr]
            if "wk431" in (a, b):
                factors = ["Q31" if derivs[0] == 3 else "Q13" if f == "Q13" else f
                           for f in factors]
            k = (tuple(ip), tuple(sorted(factors)), tuple(derivs))
            keys = [k]
            if tuple(ip) in ((1, 1), (2, 2)):
                keys.append(canon.transpose(k))
            rows.append({"ip": tuple(ip), "pos": pos, "row": row, "keys": keys,
                         "is_wk431": "wk431" in (a, b)})
    return specs, rows


def emit_chain4(target_keys, dst=None, label="v32, 27 oriented terms"):
    """Write v17 with TERM_SPECS pruned to `target_keys` (canonical keys)."""
    dst = dst or CHAIN4
    src = open(V17, encoding="utf-8").read()
    specs, rows = _v17_spec_rows(V17)
    keep, drop = {ip: [] for ip in specs}, []
    for r in rows:
        if all(k in target_keys for k in r["keys"]):
            keep[r["ip"]].append(r["row"])
        else:
            drop.append(r)
    # The file appends its four wk431 rows at import time. A restriction that
    # leaves them out must therefore also stop that append, not merely omit them
    # from the literal -- so the pruning is expressed as a REPLACEMENT of the
    # literal plus a forced NO_WK431 when no Q row survives.
    keep_wk431 = any(r["is_wk431"] for r in rows
                     if all(k in target_keys for k in r["keys"]))
    lit = "TERM_SPECS = " + _fmt_specs(
        {ip: [row for row in keep[ip]
              if not (isinstance(row[0], str) and row[0] == "wk431")]
         for ip in keep})
    start = src.index("TERM_SPECS = {")
    end = src.index("\n\n", src.index("}", src.index("TERM_SPECS = {")))
    src = src[:start] + lit + src[end:]
    if not keep_wk431:
        anchor = 'NO_WK431 = _os.environ.get("V17_NO_WK431", "0") == "1"'
        assert src.count(anchor) == 1
        src = src.replace(anchor, 'NO_WK431 = True  # program-swap: no kappa_iiij row survives')
        # and the four appends, which run regardless of the flag
        for ln in ("TERM_SPECS[(1, 1)].append(('wk431', 'ones2', _I((1, 1)), _I((3, 1)), 1.0 / 3.0))",
                   "TERM_SPECS[(2, 1)].append(('wk431', 'ones2', _I((1, 2)), _I((3, 1)), 1.0 / 6.0))",
                   "TERM_SPECS[(2, 1)].append(('wk431', 'ones2', _I((3, 2)), _I((1, 1)), 1.0 / 6.0))",
                   "TERM_SPECS[(2, 2)].append(('wk431', 'ones2', _I((1, 2)), _I((3, 2)), 1.0 / 3.0))"):
            assert src.count(ln) == 1, ln
            src = src.replace(ln, "# program-swap: dropped -- " + ln)
    os.makedirs(DIAG, exist_ok=True)
    body = BANNER % (os.path.relpath(V17, ROOT).replace("\\", "/"),
                     canon.sha256_file(V17), label,
                     canon.sha256_file(TABLE_V32) if os.path.exists(TABLE_V32) else "-")
    with open(dst, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body + src)
    return {"path": os.path.relpath(dst, ROOT).replace("\\", "/"),
            "dropped_rows": len(drop), "kept_rows": sum(len(v) for v in keep.values()),
            "wk431_kept": keep_wk431,
            "sha256": canon.sha256_file(dst)}


def _fmt_specs(specs):
    out = ["{"]
    for ip in sorted(specs, key=lambda t: (len(t), t)):
        out.append(f" {ip!r}: [")
        for row in specs[ip]:
            out.append(f"     {row!r},")
        out.append(" ],")
    out.append("}")
    return "\n".join(out)


