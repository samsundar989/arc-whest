"""RECIPROCAL COMPLETE-PROGRAM SWAP: build the four diagnostic chains.

Handoff 2026-09-17b section 1. LABEL-FREE: this module reads and writes source,
touches no truth, scores nothing, and every file it emits is a DIAGNOSTIC copy
that is never a release candidate.

THE QUESTION THIS ANSWERS, AND WHY THE EARLIER ARMS DID NOT
------------------------------------------------------------
Three enriched closures have been screened on our chain -- BUDGET 4 (141 oriented
terms), PAIR (114), BUDGET 3 + Q (57) -- and all three lost. None of them is the
program the public reference actually runs. `closure_audit/canon.py` shows why
the comparison was never decisive:

    v17's executed program (87 oriented terms) CONTAINS v32's 27 EXACTLY,
    with identical rational coefficients, and adds 60 more.

There is no term v32 has that v17 lacks. So the reference program is reachable
from ours by pure ADDITION, and the reciprocal experiment is exact in both
directions:

    chain 3 = v32's tower/feed/sketch/lambda + v17's COMPLETE pK program
    chain 4 = v17's tower/feed/lambda      + v32's pK program and nothing else

Chain 4 is chain 3 read backwards: it is v17 with its 60 extra terms deleted.
If the program carries the accuracy gap, chain 3 gains what chain 4 loses.

WHAT IS FROZEN
--------------
Reference flags (`V17_NO_FEED/NO_WK431/NO_REGEN/NO_CORR/LAM_SCALE`), the shape
gate, the correction mode, derivative conventions, orientation and masks, dtype
and backend are all left at their native values in every chain. The ONLY thing
that moves is the nonlinear moment program.

WHAT IS NOT DONE HERE, DELIBERATELY
-----------------------------------
No state is converted between backends. Each chain runs its own complete
third-order history end to end; the boundary capture in `same_state.py` supports
a ONE-STEP comparison and nothing downstream of it. There is no cross-backend
continuation and no hybrid that resumes from D3/D21 slices.

Emits (all under `_diag/`, all labelled non-release):
    closure_v17_complete.json      the canonical 87-term table, our schema
    closure_v32_only.json          v32's own 27-term table, our schema
    estimator_v17_v32prog.py       chain 4: v17 with TERM_SPECS restricted

Chain 3 is emitted by `s6_build_closure.py --table closure_v17_complete.json`,
which is the same generator the earlier closure arms used, so the two directions
share one build path.

Run:  uv run python local_sim/closure_audit/progswap.py --emit
      uv run python local_sim/closure_audit/progswap.py --verify
"""
from __future__ import annotations

