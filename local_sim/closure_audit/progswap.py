def emit():
    v32_terms, _ = canon.canon_ours(V32)
    v17_terms, _ = canon.canon_public(V17)
    missing = {k: str(c) for k, c in v32_terms.items() if v17_terms.get(k) != c}
    if missing:
        raise SystemExit(
            "v17's program does NOT contain v32's exactly, so the reciprocal "
            "swap is not a pure addition and this module's premise is wrong: %r"
            % list(missing)[:5])
    sha32 = _dump(TABLE_V32, {
        "name": "v32_only",
        "note": "the canonical program frozen v32 executes, in the generator's schema. "
                "DIAGNOSTIC: the table a v17-shaped chain is restricted to.",
        "source": {"estimator_k3_v32.py": canon.sha256_file(V32)},
        "terms": _records(v32_terms)})
    sha17 = _dump(TABLE_V17, {
        "name": "v17_complete",
        "note": "the COMPLETE canonical nonlinear moment program public v17 executes at "
                "its live 1024x16 branch (regeneration on, NO_WK431 off, NO_CORR on), "
                "expressed in this repository's own generator schema. It is a strict "
                "SUPERSET of v32's program with identical coefficients on the shared "
                "rows, so a v32 chain can execute it by addition alone. DIAGNOSTIC "
                "attribution table; no fitted constant and no reference source enters "
                "any candidate.",
        "source": {"external/504aldo/estimators/estimator_v17.py": canon.sha256_file(V17),
                   "canon.py": canon.sha256_file(os.path.join(_HERE, "canon.py"))},
        "terms": _records(v17_terms)})
    info = emit_chain4(set(v32_terms))
    ident = emit_chain4(set(v17_terms), dst=CHAIN4_ID,
                        label="v17's OWN complete program -- nothing dropped "
                              "(no-op control for the rewrite itself)")
    n_extra = len([k for k in v17_terms if k not in v32_terms])
    out = {"artifact": "closure_audit.progswap", "version": 1, "label_free": True,
           "v32_terms": len(v32_terms), "v17_terms": len(v17_terms),
           "v17_extra_over_v32": n_extra,
           "v32_subset_of_v17": True,
           "tables": {"closure_v17_complete.json": sha17,
                      "closure_v32_only.json": sha32},
           "chain4": info, "chain4_identity": ident}
    print(json.dumps(out, indent=1))
    return out


def verify():
    """Re-derive the emitted chain-4 file's canonical program and compare."""
    v32_terms, _ = canon.canon_ours(V32)
    got, _ = canon.canon_public(CHAIN4, with_wk431=False)
    extra = {k for k in got if k not in v32_terms}
    miss = {k for k in v32_terms if k not in got}
    bad = {k for k in got if k in v32_terms and got[k] != v32_terms[k]}
    ok = not extra and not miss and not bad
    print(f"chain4 canonical terms {len(got)} (v32 has {len(v32_terms)})")
    print(f"  extra {len(extra)}  missing {len(miss)}  coefficient mismatches {len(bad)}")
    if extra:
        print("  extra:", sorted(extra)[:5])
    if miss:
        print("  missing:", sorted(miss)[:5])
    # and the forward direction: the emitted table equals v17's program
    tbl = json.load(open(TABLE_V17, encoding="utf-8"))
    v17_terms, _ = canon.canon_public(V17)
    as_terms = {(tuple(t["output"]), tuple(t["factors"]), tuple(t["derivs"])):
                Fraction(t["coef"]) for t in tbl["terms"]}
    ok = ok and as_terms == v17_terms
    print(f"closure_v17_complete.json == canon(v17): {as_terms == v17_terms}")
    print("VERIFY", "OK" if ok else "FAILED")
    return 0 if ok else 1


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--emit", action="store_true")
    ap.add_argument("--verify", action="store_true")
    a = ap.parse_args()
    if a.emit:
        emit()
    if a.verify:
        return verify()
    return 0


if __name__ == "__main__":
    sys.exit(main())
