"""Emit a corrected query-objective arm from a frozen v41 source.

This is a narrow, asserted source transform.  The v41 files remain immutable:
their observed results describe their executed pre-Wick/qEd objectives.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

WICK_OLD = """    _carry_shared(out, tw, None if tw.Q is None else tw.Q * col)
    out._wts = tw._wts
    return out"""
WICK_NEW = """    _carry_shared(out, tw, None if tw.Q is None else tw.Q * col)
    # The join consumes D21 after Wick: diag(w1**2) E_pre diag(w1).
    # Its legs and Q already contain the right w1 factor; the stashed left
    # contraction factors must carry the squared row factor as well.
    if _QUERY_BASIS:
        left = col * col
        if tw._qU is not None:
            out._qU = (tw._qU[0] * left, tw._qU[1] * left)
        if tw._qold is not None:
            out._qold = tw._qold * left
    out._wts = tw._wts
    return out"""

D3_OLD = """                G = (tw.A_L[:, :n] * tw.M[:, :n]) * tw.w2b[:n]"""
D3_NEW = """                # The joining lineage follows `ko` already-shared lineages.
                # _dslice3's L summand is A_L * M * (A_L * w2b).
                c = tw.ko * n
                G = (tw.A_L[:, :n] * tw.A_L[:, :n] * tw.M[:, :n]) * tw.w2b[c:c + n]"""


def _replace_once(src: str, old: str, new: str, name: str) -> str:
    count = src.count(old)
    if count != 1:
        raise ValueError(f"{name}: expected one source anchor, found {count}")
    return src.replace(old, new, 1)


def build(src: str, *, d3: bool) -> str:
    if src.count("_QUERY_BASIS = True") != 1:
        raise ValueError("corrected objective requires a query-basis arm")
    src = _replace_once(src, WICK_OLD, WICK_NEW, "post-Wick left factors")
    if d3:
        if "_QB_D3 = 0" in src:
            src = _replace_once(src, "_QB_D3 = 0", "_QB_D3 = 16", "D3 reserved rank")
        elif src.count("_QB_D3 = 16") != 1:
            raise ValueError("D3 arm requires exactly 16 reserved columns")
        src = _replace_once(src, D3_OLD, D3_NEW, "D3 joining lineage")
    elif D3_OLD not in src:
        raise ValueError("missing existing D3 source anchor")
    return src


def emit(base: Path, output: Path, *, d3: bool) -> str:
    raw = base.read_bytes()
    source = build(raw.decode("utf-8"), d3=d3)
    header = (f'"""{output.name}: corrected post-Wick consumed-query objective.\n'
              f'Generated by local_sim/s13_correct_query_objective.py from {base.name}\n'
              f'base sha256 {hashlib.sha256(raw).hexdigest()}. DO NOT EDIT.\n'
              'Not approved for submission.\n\n')
    first = source.find('"""')
    source = header + source[first + 3:]
    output.write_text(source, encoding="utf-8", newline="\n")
    return hashlib.sha256(output.read_bytes()).hexdigest()


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", type=Path, required=True)
    ap.add_argument("--output", type=Path, required=True)
    ap.add_argument("--d3", action="store_true")
    args = ap.parse_args()
    print(emit(args.base, args.output, d3=args.d3))
