"""P4 exact-cost variants: patches applied to any generated v31-family text.

Each toggle is an EXACT transformation in real arithmetic (float32 reassociation
only), so it is certified by ledger diff + tiny parity + one DESIGN run under the
already-authorized process (handoff 09-14 section 0.3), never by a fitted constant.

  _P4_FINAL_VAR  last layer: the grader reads means only, so `cov_pre` is never
                 needed there -- only its diagonal: var = rowsum((W^T C) . W^T).
                 Saves one (n,n)@(n,n) product.
  _P4_BLOCKSYM   `cov_pre = (W^T C) W` is symmetric: compute the top half-row
                 block and the bottom-right quarter, mirror the bottom-left.
                 3/4 of the second product.
  _STRASSEN_DEPTH / _STRASSEN_MIN_BLOCK are already module knobs in every file.

Use: `build(text, final_var=True, blocksym=True, depth=None, min_block=None)`.
"""

from __future__ import annotations

_SYM = '''
def _p4_sym_sandwich(WT, cov, W):
    """`W^T C W` for symmetric `C`, paying 3/4 of the second product.

    Rows `[:h]` give blocks 11 and 12 in one product; block 22 is its own
    quarter product; block 21 is block 12 transposed -- exact in real
    arithmetic because the result is symmetric. Odd width: plain product.
    """
    X = _mm(WT, cov)
    n = X.shape[0]
    if n % 2:
        return _mm(X, W)
    h = n // 2
    top = _mm(X[:h], W)
    b22 = _mm(X[h:], W[:, h:])
    return fnp.concatenate([top, fnp.concatenate([top[:, h:].T, b22], axis=1)], axis=0)


'''


def build(text, final_var=True, blocksym=True, depth=None, min_block=None, tag="P4"):
    old = '''    cov_pre = _mm(_mm(WT, cov), W)                            # 2 matmuls
    metric = float(init_scale)

    var = fnp.maximum(fnp.diagonal(cov_pre), dtype(1e-12))'''
    new = '''    if _P4_FINAL_VAR and last_layer:
        # P4: the last layer reads means only -- the diagonal of W^T C W is
        # rowsum((W^T C) . W^T), one product instead of two.
        _X4 = _mm(WT, cov)
        cov_pre = None
        var = fnp.maximum((_X4 * WT).sum(axis=1), dtype(1e-12))
    else:
        cov_pre = (_p4_sym_sandwich(WT, cov, W) if _P4_BLOCKSYM
                   else _mm(_mm(WT, cov), W))
        var = fnp.maximum(fnp.diagonal(cov_pre), dtype(1e-12))
    metric = float(init_scale)'''
    if text.count(old) != 1:
        raise SystemExit("P4 anchor (cov_pre) not unique")
    text = text.replace(old, new, 1)
    fa = "def _dslice3(tw):"
    if text.count(fa) != 1:
        raise SystemExit("P4 cannot place helper")
    text = text.replace(fa, _SYM.lstrip("\n") + fa, 1)
    anchor = "_P2_SEPARABLE = True\n"
    if text.count(anchor) != 1:
        raise SystemExit("P4 constants anchor not unique")
    text = text.replace(anchor, anchor + "\n#: P4 exact-cost toggles (local_sim/s4_build_p4.py)\n"
                        "_P4_FINAL_VAR = %r\n_P4_BLOCKSYM = %r\n" % (bool(final_var), bool(blocksym)), 1)
    if depth is not None:
        a = "_STRASSEN_DEPTH = 4\n"
        if text.count(a) != 1:
            raise SystemExit("depth anchor")
        text = text.replace(a, "_STRASSEN_DEPTH = %d\n" % int(depth), 1)
    if min_block is not None:
        a = "_STRASSEN_MIN_BLOCK = 64\n"
        if text.count(a) != 1:
            raise SystemExit("min block anchor")
        text = text.replace(a, "_STRASSEN_MIN_BLOCK = %d\n" % int(min_block), 1)
    # the budget guard: the savings are not credited (over-predicting is safe)
    return text.replace("GENERATED by `local_sim/", "GENERATED (+%s) by `local_sim/" % tag, 1)
